#!/usr/bin/env python3
"""Generate the Opus fixture manifest from ffprobe output and Ogg packets.

Test-only tooling.  Not part of the library or its build.  It resolves the
fixtures relative to this file, so it can be run from anywhere:

    python3 gen_manifest.py > manifest.txt

The script parses the Ogg pages only to observe the TOC configuration and
frame-count code of every audio packet; packet sizes and durations come from
ffprobe, which is treated as an external behavioral oracle.
"""
import json
import struct
import subprocess
import sys
from pathlib import Path

FIXTURE_DIR = Path(__file__).resolve().parent
FIXTURES = sorted(FIXTURE_DIR.glob("*.opus"))
if not FIXTURES:
    raise SystemExit(f"no .opus fixtures found in {FIXTURE_DIR}")


def probe(name):
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_packets", "-show_streams", "-of", "json", name],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def first_packet(data):
    """Return the first two packets (headers) and the audio packets."""
    packets = []
    current = bytearray()
    pending = False
    off = 0
    while off < len(data):
        assert data[off : off + 4] == b"OggS"
        header_type = data[off + 5]
        nsegs = data[off + 26]
        lacing = data[off + 27 : off + 27 + nsegs]
        body_off = off + 27 + nsegs
        body = data[body_off : body_off + sum(lacing)]
        assert bool(header_type & 0x01) == pending
        pos = 0
        for lace in lacing:
            current += body[pos : pos + lace]
            pos += lace
            if lace < 255:
                packets.append(bytes(current))
                current = bytearray()
                pending = False
            else:
                pending = True
        off = body_off + sum(lacing)
    return packets[0], packets[1], packets[2:]


def main():
    print("# Opus/Ogg fixture manifest generated by gen_manifest.py.")
    print("# Sizes and durations are ffprobe reference values; configs and codes")
    print("# were observed by parsing the TOC byte of every extracted audio packet.")
    for name in FIXTURES:
        data = name.read_bytes()
        head, tags, audio = first_packet(data)
        assert head[:8] == b"OpusHead", name
        assert tags[:8] == b"OpusTags", name
        channels = head[9]
        pre_skip = struct.unpack_from("<H", head, 10)[0]
        info = probe(str(name))
        stream = info["streams"][0]
        packets = info["packets"]
        assert len(packets) == len(audio), (name, len(packets), len(audio))
        sizes = [int(p["size"]) for p in packets]
        durations = [int(p["duration"]) for p in packets]
        frame_samples = max(durations)
        assert all(d == frame_samples for d in durations[:-1]), name
        duration_ts = int(stream["duration_ts"])
        end_trim = frame_samples - durations[-1]
        assert len(packets) * frame_samples - end_trim == duration_ts, (
            name,
            len(packets) * frame_samples,
            end_trim,
            duration_ts,
        )
        assert sizes == [len(p) for p in audio], name
        configs = {}
        codes = {}
        for packet in audio:
            toc = packet[0]
            configs[toc >> 3] = configs.get(toc >> 3, 0) + 1
            code = toc & 3
            codes[code] = codes.get(code, 0) + 1
        print(f"fixture {name.name}")
        print(f"channels {channels}")
        print(f"pre_skip {pre_skip}")
        print(f"frame_samples {frame_samples}")
        print(f"duration_ts {duration_ts}")
        print(f"coded_samples {len(packets) * frame_samples}")
        print("configs " + " ".join(f"{k}:{v}" for k, v in sorted(configs.items())))
        print("codes " + " ".join(f"{k}:{v}" for k, v in sorted(codes.items())))
        print("sizes " + " ".join(str(s) for s in sizes))
        print(
            "durations " + " ".join(str(d) for d in durations)
        )
        print("end")


if __name__ == "__main__":
    sys.exit(main())
