//! Intra prediction for H.266/VVC (ITU-T Rec. H.266 §8.4).
//!
//! Algorithms and tables derived from VTM 24.0 (`IntraPrediction.cpp`,
//! `InterpolationFilter.cpp`, `UnitTools.cpp`, `MatrixIntraPrediction.cpp`,
//! `MipData.h`, BSD-3-Clause, Copyright (c) 2010-2026 ITU/ISO/IEC).
//! See `THIRD_PARTY.md`.
//!
//! Supported tools:
//! - Planar (mode 0) and DC (mode 1) intra prediction (§8.4.5.2.10, §8.4.5.2.11).
//! - All 65 directional angular intra prediction modes `2..=66` (§8.4.5.2.12).
//! - Wide-angle intra prediction mode mapping `-14..=-1` and `67..=80` for
//!   non-square blocks (§8.4.5.2.7, Table 26).
//! - 4-tap cubic (`CHROMA_FILTER_4TAP`) and 4-tap Gaussian reference sample
//!   interpolation filters for luma, 2-tap linear filter for chroma, and
//!   `[1, 2, 1] / 4` reference smoothing (§8.4.5.2.8, §8.4.5.2.12).
//! - Position-Dependent Intra Prediction Combination (PDPC, §8.4.5.2.14) for
//!   Planar, DC, pure horizontal/vertical (`intra_pred_angle == 0`), and
//!   positive-angle directional modes (`intra_pred_angle > 0`).
//! - 6-entry Most Probable Mode (MPM) candidate list derivation (§8.4.2).
//! - Multiple Reference Line (MRL) intra prediction (`mrl_idx` 0..=2, §8.4.5.2.2).
//! - Intra Sub-Partitions (ISP, horizontal and vertical 2/4 splits, §8.4.5.1).
//! - Cross-Component Linear Model (CCLM: `LM_CHROMA_IDX = 67`, `MDLM_L_IDX = 68`,
//!   `MDLM_T_IDX = 69`, §8.4.5.2.13) with 4-point min/max group sorting and
//!   `CCLM_DIV_SIG_TABLE` lookup.
//! - Matrix-based Intra Prediction (MIP, `S0`/`S1`/`S2` size classes, §8.4.5.2.1).
//! - Block DPCM (BDPCM, horizontal and vertical unfiltered sample prediction, §8.4.5.2.6).

