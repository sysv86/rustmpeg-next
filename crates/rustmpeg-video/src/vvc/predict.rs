/// A single reconstructed plane.
///
/// Crate-internal: the decoder validates dimensions and plane lengths before
/// construction, so the unchecked indexing in [`Plane::get`] and [`Plane::set`]
/// is only reachable through validated block geometry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Plane {
    /// Plane width in samples.
    pub width: usize,
    /// Plane height in samples.
    pub height: usize,
    /// Row-major 8-bit sample buffer (`width * height`).
    pub data: Vec<u8>,
}

impl Plane {
    /// Allocate a zero-filled plane.
    pub fn new(width: usize, height: usize) -> Self {
        Self {
            width,
            height,
            data: vec![0; width * height],
        }
    }

    /// Copy `data` into a plane, or return `None` when the length disagrees.
    pub fn from_slice(width: usize, height: usize, data: &[u8]) -> Option<Self> {
        let expected = width.checked_mul(height)?;
        if data.len() != expected {
            return None;
        }
        Some(Self {
            width,
            height,
            data: data.to_vec(),
        })
    }

    /// Read one sample inside the plane.
    #[inline]
    pub fn get(&self, x: usize, y: usize) -> u8 {
        self.data[y * self.width + x]
    }

    /// Write one sample inside the plane.
    #[inline]
    pub fn set(&mut self, x: usize, y: usize, value: u8) {
        let idx = y * self.width + x;
        self.data[idx] = value;
    }
}

/// Reference samples for one intra prediction block.
#[derive(Debug, Clone)]
pub struct RefSamples {
    /// `2 * w` samples above the block (`above[0]` is directly above `x = 0`).
    pub above: Vec<i32>,
    /// `2 * h` samples left of the block (`left[0]` is directly left of `y = 0`).
    pub left: Vec<i32>,
    /// Top-left corner reference sample at `(-1, -1)`.
    pub top_left: i32,
}

/// Extended reference samples for Multiple Reference Line (MRL) intra prediction
/// (`mrl_idx` in `0..=2`, H.266 §8.4.5.2.2, VTM `IntraPrediction.cpp:468-530`).
#[derive(Debug, Clone)]
pub struct MrlRefSamples {
    /// Reference line index (`0`, `1`, or `2`).
    pub mrl_idx: usize,
    /// Unfiltered row 0 buffer `pSrc.at(x, 0)` of length `2 * w + 1 + mrl_idx + 4`.
    pub row_above: Vec<i32>,
    /// Unfiltered row 1 buffer `pSrc.at(y, 1)` of length `2 * h + 1 + mrl_idx + 4`.
    pub row_left: Vec<i32>,
}

impl MrlRefSamples {
    /// Convert a standard `RefSamples` (`mrl_idx == 0`) into `MrlRefSamples`.
    pub fn from_ref_samples(refs: &RefSamples) -> Self {
        let mut row_above = Vec::with_capacity(refs.above.len() + 5);
        row_above.push(refs.top_left);
        row_above.extend_from_slice(&refs.above);
        let last_a = *row_above.last().unwrap_or(&128);
        row_above.resize(refs.above.len() + 5, last_a);

        let mut row_left = Vec::with_capacity(refs.left.len() + 5);
        row_left.push(refs.top_left);
        row_left.extend_from_slice(&refs.left);
        let last_l = *row_left.last().unwrap_or(&128);
        row_left.resize(refs.left.len() + 5, last_l);

        Self {
            mrl_idx: 0,
            row_above,
            row_left,
        }
    }
}

/// Collect reference samples for a `w x h` block at `(bx, by)`.
///
/// `unit` is the minimum prediction unit in the component's coordinates: 4 for
/// luma and 2 for 4:2:0 chroma. Availability is resolved against the already
/// reconstructed plane, then padded like VTM's `xFillReferenceSamples`.
pub fn gather_references(recon: &Plane, bx: usize, by: usize, w: usize, h: usize) -> RefSamples {
    let pw = recon.width;
    let ph = recon.height;
    let mut above = vec![0i32; 2 * w];
    let mut left = vec![0i32; 2 * h];

    let above_len = if by == 0 { 0 } else { (pw - bx).min(2 * w) };
    let left_len = if bx == 0 { 0 } else { (ph - by).min(h) };

    if above_len > 0 {
        for (i, a) in above.iter_mut().take(above_len).enumerate() {
            *a = i32::from(recon.get(bx + i, by - 1));
        }
    }
    if left_len > 0 {
        for (i, l) in left.iter_mut().take(left_len).enumerate() {
            *l = i32::from(recon.get(bx - 1, by + i));
        }
    }

    let top_left = if above_len > 0 && left_len > 0 {
        i32::from(recon.get(bx - 1, by - 1))
    } else if above_len > 0 {
        above[0]
    } else if left_len > 0 {
        left[0]
    } else {
        128
    };

    if above_len == 0 {
        above.fill(if left_len > 0 { left[0] } else { 128 });
    } else {
        for i in above_len..2 * w {
            above[i] = above[above_len - 1];
        }
    }
    if left_len == 0 {
        left.fill(if above_len > 0 { above[0] } else { 128 });
    } else {
        for i in left_len..2 * h {
            left[i] = left[left_len - 1];
        }
    }

    RefSamples {
        above,
        left,
        top_left,
    }
}

/// Collect reference samples for Multiple Reference Line (MRL) intra prediction
/// (`mrl_idx` in `0..=2`, H.266 §8.4.5.2.2, VTM `IntraPrediction.cpp:919-1167`).
///
/// Per H.266 §8.4.5.2.2, when a block lies in the first row of a CTU
/// (`(by & (ctu_size - 1)) == 0`), `mrl_idx` is forced to `0`.
pub fn gather_references_mrl(
    recon: &Plane,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    mrl_idx: usize,
    ctu_size: usize,
) -> MrlRefSamples {
    let effective_mrl = if ctu_size > 0 && (by & (ctu_size - 1)) == 0 {
        0
    } else {
        mrl_idx.min(2)
    };
    if effective_mrl == 0 {
        return MrlRefSamples::from_ref_samples(&gather_references(recon, bx, by, w, h));
    }

    let pw = recon.width;
    let ph = recon.height;
    let offset = 1 + effective_mrl;
    let above_total = 2 * w + offset;
    let left_total = 2 * h + offset;
    let mut row_above = vec![128i32; above_total + 4];
    let mut row_left = vec![128i32; left_total + 4];

    let has_above = by >= offset;
    let has_left = bx >= offset;

    if has_above && has_left {
        let tl = i32::from(recon.get(bx - offset, by - offset));
        row_above[0] = tl;
        row_left[0] = tl;
        for i in 1..=effective_mrl {
            row_above[i] = i32::from(recon.get(bx - offset + i, by - offset));
            row_left[i] = i32::from(recon.get(bx - offset, by - offset + i));
        }
    }

    let avail_above = if has_above { (pw - bx).min(2 * w) } else { 0 };
    let avail_left = if has_left { (ph - by).min(h) } else { 0 };

    if avail_above > 0 {
        for x in 0..avail_above {
            row_above[offset + x] = i32::from(recon.get(bx + x, by - offset));
        }
        let last = row_above[offset + avail_above - 1];
        for x in (offset + avail_above)..row_above.len() {
            row_above[x] = last;
        }
    }
    if avail_left > 0 {
        for y in 0..avail_left {
            row_left[offset + y] = i32::from(recon.get(bx - offset, by + y));
        }
        let last = row_left[offset + avail_left - 1];
        for y in (offset + avail_left)..row_left.len() {
            row_left[y] = last;
        }
    }

    if !has_above || !has_left {
        let pad_tl = if avail_above > 0 {
            row_above[offset]
        } else if avail_left > 0 {
            row_left[offset]
        } else {
            128
        };
        for i in 0..offset {
            row_above[i] = pad_tl;
            row_left[i] = pad_tl;
        }
        if avail_above == 0 {
            row_above.fill(pad_tl);
        }
        if avail_left == 0 {
            row_left.fill(pad_tl);
        }
    }

    MrlRefSamples {
        mrl_idx: effective_mrl,
        row_above,
        row_left,
    }
}

impl RefSamples {
    /// `[1 2 1]` smoothing of both reference rows (VTM `xFilterReferenceSamples`,
    /// `IntraPrediction.cpp:1169-1203`).
    #[allow(clippy::needless_range_loop)]
    pub fn filtered(&self) -> RefSamples {
        let w2 = self.above.len();
        let h2 = self.left.len();
        let mut above = self.above.clone();
        let mut left = self.left.clone();

        let top_left = (2 * self.top_left + self.above[0] + self.left[0] + 2) >> 2;
        for j in 0..w2.saturating_sub(1) {
            let prev = if j == 0 {
                self.top_left
            } else {
                self.above[j - 1]
            };
            above[j] = (prev + 2 * self.above[j] + self.above[j + 1] + 2) >> 2;
        }
        if w2 > 0 {
            above[w2 - 1] = self.above[w2 - 1];
        }
        for j in 0..h2.saturating_sub(1) {
            let prev = if j == 0 {
                self.top_left
            } else {
                self.left[j - 1]
            };
            left[j] = (prev + 2 * self.left[j] + self.left[j + 1] + 2) >> 2;
        }
        if h2 > 0 {
            left[h2 - 1] = self.left[h2 - 1];
        }
        RefSamples {
            above,
            left,
            top_left,
        }
    }
}

#[inline]
fn log2_exact(value: usize) -> u32 {
    debug_assert!(value.is_power_of_two());
    value.trailing_zeros()
}

#[inline]
fn floor_log2_u32(v: u32) -> i32 {
    debug_assert!(v > 0);
    31 - v.leading_zeros() as i32
}

/// Luma planar uses `[1 2 1]`-filtered references when `w * h > 32`; chroma
/// never filters. DC never filters either.
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.10 (`filterFlag`: `refIdx == 0`,
/// `nTbW * nTbH > 32`, `cIdx == 0`, no ISP split, and `refFilterFlag == 1`).
pub fn uses_reference_filter(is_luma: bool, mode: IntraMode, w: usize, h: usize) -> bool {
    match mode {
        IntraMode::Planar => is_luma && w * h > 32,
        IntraMode::Dc => false,
        IntraMode::Angular(dir) => is_luma && w * h > 32 && should_filter_ref_angular(w, h, dir),
    }
}

/// Luma `refFilterFlag` for a directional mode (`2..=66`): `true` when the
/// `[1 2 1] / 4` reference filter is selected instead of the 4-tap Gaussian
/// interpolation filter.
///
/// The flag is taken from the same derived parameters that predict the block
/// (`init_angular_params`), so an encoder decision and a decoder reconstruction
/// cannot disagree. After the §8.4.5.2.7 wide-angle mapping it selects the
/// integer-slope directions listed in H.266 §8.4.5.2.6 (`2`, `34`, `66` for square
/// blocks, plus the wide-angle extensions).
pub fn should_filter_ref_angular(w: usize, h: usize, dir: u8) -> bool {
    init_angular_params(dir, w, h, w, h, true, 0, false).ref_filter_flag
}

/// Intra prediction mode supported by the baseline subset encoder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IntraMode {
    /// PLANAR (mode 0).
    Planar,
    /// DC (mode 1).
    Dc,
    /// Directional angular mode (`2..=66`).
    Angular(u8),
}

/// Full H.266/VVC intra prediction mode across luma and chroma blocks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IntraPredMode {
    /// `INTRA_PLANAR` (mode 0).
    Planar,
    /// `INTRA_DC` (mode 1).
    Dc,
    /// Directional angular mode `2..=66`.
    Angular(u8),
    /// Cross-component linear model `INTRA_LT_CCLM` (mode 67).
    LmChroma,
    /// Left-only multi-directional linear model `INTRA_L_CCLM` (mode 68).
    MdlmL,
    /// Top-only multi-directional linear model `INTRA_T_CCLM` (mode 69).
    MdlmT,
    /// Matrix-based intra prediction (MIP, H.266 §8.4.5.2.1).
    Mip {
        /// MIP matrix mode index (`0..16` for `S0`, `0..8` for `S1`, `0..6` for `S2`).
        mode_idx: u8,
        /// Whether boundary and output are transposed (`intra_mip_transposed_flag`).
        transposed: bool,
    },
    /// Block DPCM (`intra_bdpcm_luma_flag` / `intra_bdpcm_chroma_flag`, H.266 §8.4.5.2.6).
    Bdpcm {
        /// `false` for horizontal BDPCM, `true` for vertical BDPCM.
        vertical: bool,
    },
}

impl From<IntraMode> for IntraPredMode {
    fn from(mode: IntraMode) -> Self {
        match mode {
            IntraMode::Planar => Self::Planar,
            IntraMode::Dc => Self::Dc,
            IntraMode::Angular(dir) => Self::Angular(dir),
        }
    }
}

impl IntraPredMode {
    /// Construct an `IntraPredMode` from a standard mode index (`0..=69`).
    pub fn from_mode_index(idx: u8) -> Option<Self> {
        match idx {
            0 => Some(Self::Planar),
            1 => Some(Self::Dc),
            2..=66 => Some(Self::Angular(idx)),
            67 => Some(Self::LmChroma),
            68 => Some(Self::MdlmL),
            69 => Some(Self::MdlmT),
            _ => None,
        }
    }

    /// Return the mode index (`0..=69`), or `0` (Planar) for MIP / `VER_IDX`/`HOR_IDX` for BDPCM.
    pub fn mode_index(self) -> u8 {
        match self {
            Self::Planar => PLANAR_IDX,
            Self::Dc => DC_IDX,
            Self::Angular(m) => m,
            Self::LmChroma => LM_CHROMA_IDX,
            Self::MdlmL => MDLM_L_IDX,
            Self::MdlmT => MDLM_T_IDX,
            Self::Mip { .. } => PLANAR_IDX,
            Self::Bdpcm { vertical } => {
                if vertical {
                    VER_IDX
                } else {
                    HOR_IDX
                }
            }
        }
    }
}

/// Check whether an angular slope `abs_ang` is an integer multiple of 32
/// (`(abs_ang & 0x1F) == 0`, VTM `IntraPrediction.h:128`).
#[inline]
pub fn is_integer_slope(abs_ang: i32) -> bool {
    (abs_ang & 0x1F) == 0
}

/// Map a standard directional intra mode (`2..=66`) to its wide-angle mode
/// (`-14..=80`) for rectangular blocks of size `(w, h)`.
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.7 Table 26 (PDF p. 266);
/// VTM `IntraPrediction.cpp:180-200` (`getModifiedWideAngle`).
pub fn get_modified_wide_angle(w: usize, h: usize, pred_mode: u8) -> i32 {
    let mode = i32::from(pred_mode);
    if pred_mode > DC_IDX && pred_mode <= VDIA_IDX {
        const MODE_SHIFT: [i32; 6] = [0, 6, 10, 12, 14, 15];
        let log2_w = floor_log2_u32(w as u32);
        let log2_h = floor_log2_u32(h as u32);
        let delta_size = (log2_w - log2_h).unsigned_abs() as usize;
        if delta_size < MODE_SHIFT.len() {
            let shift = MODE_SHIFT[delta_size];
            if w > h && mode < 2 + shift {
                return mode + (i32::from(VDIA_IDX) - 1);
            } else if h > w && mode > i32::from(VDIA_IDX) - shift {
                return mode - (i32::from(VDIA_IDX) - 1);
            }
        }
    }
    mode
}

/// Derive the 6-entry Most Probable Mode (MPM) candidate list for a luma block
/// from the intra modes of its left (`left_dir`) and above (`above_dir`) neighbors.
///
/// Neighbors that are unavailable, outside the current CTU row (for `above`),
/// MIP-coded, or inter-coded pass `None` (which defaults to `PLANAR_IDX = 0`).
///
/// Normative source: ITU-T Rec. H.266 §8.4.2 (PDF pp. 244–247);
/// VTM `UnitTools.cpp:598-689` (`PU::getIntraMPMs`).
pub fn derive_intra_mpms(left_dir: Option<u8>, above_dir: Option<u8>) -> [u8; 6] {
    let left = i32::from(left_dir.unwrap_or(PLANAR_IDX).min(VDIA_IDX));
    let above = i32::from(above_dir.unwrap_or(PLANAR_IDX).min(VDIA_IDX));

    let wrap = |m: i32| -> u8 {
        const MOD: i32 = 64; // NUM_INTRA_ANGULAR_MODES - 1
        (((m - i32::from(ANGULAR_BASE) + MOD) % MOD) + i32::from(ANGULAR_BASE)) as u8
    };

    let num_cands = if left == above { 1 } else { 2 };
    let min_cand = left.min(above);
    let max_cand = left.max(above);

    let mut mpm = [PLANAR_IDX; 6];
    mpm[0] = PLANAR_IDX;

    if max_cand < i32::from(ANGULAR_BASE) {
        mpm[1] = DC_IDX;
        mpm[2] = VER_IDX;
        mpm[3] = HOR_IDX;
        mpm[4] = VER_IDX - 4;
        mpm[5] = VER_IDX + 4;
    } else if num_cands == 1 || min_cand < i32::from(ANGULAR_BASE) {
        mpm[1] = max_cand as u8;
        mpm[2] = wrap(max_cand - 1);
        mpm[3] = wrap(max_cand + 1);
        mpm[4] = wrap(max_cand - 2);
        mpm[5] = wrap(max_cand + 2);
    } else {
        mpm[1] = left as u8;
        mpm[2] = above as u8;
        if max_cand - min_cand == 1 {
            mpm[3] = wrap(min_cand - 1);
            mpm[4] = wrap(max_cand + 1);
            mpm[5] = wrap(min_cand - 2);
        } else if max_cand - min_cand >= 62 {
            // NUM_INTRA_ANGULAR_MODES - 3 = 65 - 3 = 62
            mpm[3] = wrap(min_cand + 1);
            mpm[4] = wrap(max_cand - 1);
            mpm[5] = wrap(min_cand + 2);
        } else if max_cand - min_cand == 2 {
            mpm[3] = wrap(min_cand + 1);
            mpm[4] = wrap(min_cand - 1);
            mpm[5] = wrap(max_cand + 1);
        } else {
            mpm[3] = wrap(min_cand - 1);
            mpm[4] = wrap(min_cand + 1);
            mpm[5] = wrap(max_cand - 1);
        }
    }
    mpm
}

/// Map a non-MPM remainder index (`0..61`, decoded via 60-symbol truncated binary)
/// to the actual luma intra prediction mode (`0..=66`), given the 6 MPM candidates.
///
/// Normative source: ITU-T Rec. H.266 §8.4.2; VTM `CABACReader.cpp:1367-1402`.
pub fn resolve_non_mpm_luma_mode(rem_idx: u8, mpm: &[u8; 6]) -> u8 {
    let mut sorted = *mpm;
    sorted.sort_unstable();
    let mut mode = rem_idx;
    for &m in &sorted {
        if mode >= m {
            mode += 1;
        }
    }
    mode
}

/// Encode a luma intra prediction mode (`0..=66`) against the 6-entry MPM list,
/// returning `Ok(mpm_idx)` (`0..6`) if in the MPM list or `Err(rem_idx)` (`0..61`)
/// if coded via the non-MPM truncated binary path.
pub fn classify_luma_mode_mpm(mode: u8, mpm: &[u8; 6]) -> Result<usize, u8> {
    if let Some(pos) = mpm.iter().position(|&m| m == mode) {
        return Ok(pos);
    }
    let mut sorted = *mpm;
    sorted.sort_unstable();
    // Inverse of `resolve_non_mpm_luma_mode` / VTM
    // `CABACWriter::intra_luma_pred_mode`: walk the sorted MPMs downwards and
    // decrement the remaining symbol whenever it is still above an MPM.
    let mut rem = mode;
    for &m in sorted.iter().rev() {
        if rem > m {
            rem -= 1;
        }
    }
    Err(rem)
}

/// Derive the 4 non-DM, non-CCLM chroma candidate modes (`[PLANAR, VER, HOR, DC]`
/// with any match against `luma_mode` replaced by `VDIA_IDX = 66`).
///
/// Normative source: ITU-T Rec. H.266 §8.4.3 Table 22 (PDF p. 248);
/// VTM `UnitTools.cpp:722-748` (`PU::getIntraChromaCandModes`).
pub fn derive_chroma_cand_modes(luma_mode: u8, is_dm_mip: bool) -> [u8; 4] {
    let mut cands = [PLANAR_IDX, VER_IDX, HOR_IDX, DC_IDX];
    if !is_dm_mip {
        for c in &mut cands {
            if *c == luma_mode {
                *c = VDIA_IDX;
                break;
            }
        }
    }
    cands
}

/// Resolve the final chroma intra prediction mode from `chroma_dir` and co-located `luma_mode`.
///
/// Normative source: ITU-T Rec. H.266 §8.4.3; VTM `UnitTools.cpp:774-788`.
pub fn resolve_final_chroma_mode(chroma_dir: u8, luma_mode: u8, is_422: bool) -> u8 {
    let mut mode = if chroma_dir == DM_CHROMA_IDX {
        luma_mode
    } else {
        chroma_dir
    };
    if is_422 && (mode as usize) < CHROMA_422_INTRA_ANGLE_MAPPING_TABLE.len() {
        mode = CHROMA_422_INTRA_ANGLE_MAPPING_TABLE[mode as usize];
    }
    mode
}

/// Derived parameters for angular intra prediction (`IntraPrediction.cpp:369-440`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AngularParams {
    /// Modified wide-angle mode (`-14..=80`).
    pub pred_mode: i32,
    /// `true` if vertical-like (`pred_mode >= DIA_IDX = 34`), `false` if horizontal-like.
    pub is_mode_ver: bool,
    /// Signed angle step in 1/32-pel units (`-1024..=1024`).
    pub intra_pred_angle: i32,
    /// Inverse angle `Round((512 * 32) / |intra_pred_angle|)`.
    pub abs_inv_angle: i32,
    /// Whether `[1, 2, 1] / 4` reference sample filtering is applied before prediction.
    pub ref_filter_flag: bool,
    /// Whether the 4-tap Gaussian smoothing filter (`true`) or 4-tap cubic filter (`false`) is used.
    pub interpolation_flag: bool,
    /// Whether PDPC post-filtering is applied (`IntraPrediction.cpp:386-412`).
    pub apply_pdpc: bool,
    /// Angular PDPC shift scale (`0..=2`).
    pub angular_scale: i32,
}

/// Initialize intra prediction parameters for a directional mode (`2..=66`).
///
/// `cu_w` and `cu_h` are the parent CU dimensions (which differ from `pu_w`, `pu_h`
/// when ISP is active, per VTM `IntraPrediction.cpp:376-380`).
pub fn init_angular_params(
    dir_mode: u8,
    pu_w: usize,
    pu_h: usize,
    cu_w: usize,
    cu_h: usize,
    is_luma: bool,
    mrl_idx: usize,
    use_isp: bool,
) -> AngularParams {
    let (block_w, block_h) = if use_isp && is_luma {
        (cu_w, cu_h)
    } else {
        (pu_w, pu_h)
    };
    let pred_mode = get_modified_wide_angle(block_w, block_h, dir_mode);
    let is_mode_ver = pred_mode >= i32::from(DIA_IDX);
    let multi_ref_index = if is_luma { mrl_idx } else { 0 };
    let mut ref_filter_flag = false;
    let mut interpolation_flag = false;
    let mut apply_pdpc = pu_w >= 4 && pu_h >= 4 && multi_ref_index == 0;

    let intra_pred_angle_mode = if is_mode_ver {
        pred_mode - i32::from(VER_IDX)
    } else {
        -(pred_mode - i32::from(HOR_IDX))
    };

    let abs_ang_mode = intra_pred_angle_mode.unsigned_abs() as usize;
    let sign_ang = if intra_pred_angle_mode < 0 { -1 } else { 1 };
    let abs_ang = ANG_TABLE[abs_ang_mode.min(31)];
    let abs_inv_angle = INV_ANG_TABLE[abs_ang_mode.min(31)];
    let intra_pred_angle = sign_ang * abs_ang;

    let mut angular_scale = 0;
    if intra_pred_angle_mode < 0 {
        apply_pdpc = false;
    } else if intra_pred_angle_mode > 0 {
        let side_size = if is_mode_ver { pu_h } else { pu_w };
        let inv_term = floor_log2_u32((3 * abs_inv_angle - 2).max(1) as u32) - 8;
        angular_scale = 2.min(floor_log2_u32(side_size as u32) - inv_term);
        if angular_scale < 0 {
            apply_pdpc = false;
        }
    }

    if is_luma && !use_isp && multi_ref_index == 0 && dir_mode != DC_IDX && dir_mode != PLANAR_IDX {
        let diff = (pred_mode - i32::from(HOR_IDX))
            .abs()
            .min((pred_mode - i32::from(VER_IDX)).abs());
        let log2_size = ((floor_log2_u32(pu_w as u32) + floor_log2_u32(pu_h as u32)) >> 1) as usize;
        if diff > INTRA_FILTER_THRESHOLD[log2_size.min(7)] {
            let is_ref_filter = is_integer_slope(abs_ang);
            ref_filter_flag = is_ref_filter;
            interpolation_flag = !is_ref_filter;
        }
    }

    AngularParams {
        pred_mode,
        is_mode_ver,
        intra_pred_angle,
        abs_inv_angle,
        ref_filter_flag,
        interpolation_flag,
        apply_pdpc,
        angular_scale,
    }
}

/// PLANAR prediction (VTM `xPredIntraPlanar`, `IntraPrediction.cpp:294-353`).
pub fn predict_planar(refs: &RefSamples, w: usize, h: usize) -> Vec<i32> {
    let log2w = log2_exact(w);
    let log2h = log2_exact(h);
    let offset = 1i32 << (log2w + log2h);
    let final_shift = 1 + log2w + log2h;

    let mut top: Vec<i32> = refs.above[..=w].to_vec();
    let mut left: Vec<i32> = refs.left[..=h].to_vec();
    let top_right = top[w];
    let bottom_left = left[h];

    let bottom_row: Vec<i32> = (0..w).map(|k| bottom_left - top[k]).collect();
    let right_column: Vec<i32> = (0..h).map(|k| top_right - left[k]).collect();
    for value in top.iter_mut() {
        *value <<= log2h;
    }
    for value in left.iter_mut() {
        *value <<= log2w;
    }

    let mut pred = vec![0i32; w * h];
    for y in 0..h {
        let mut hor = left[y];
        for x in 0..w {
            hor += right_column[y];
            top[x] += bottom_row[x];
            let vert = top[x];
            pred[y * w + x] = ((hor << log2h) + (vert << log2w) + offset) >> final_shift;
        }
    }
    pred
}

/// DC prediction (VTM `xGetPredValDc`, `IntraPrediction.cpp:355-359`).
pub fn predict_dc(refs: &RefSamples, w: usize, h: usize) -> Vec<i32> {
    let denom = if w == h { w << 1 } else { w.max(h) };
    let div_shift = log2_exact(denom);
    let div_offset = (denom >> 1) as i32;
    let mut sum = 0i32;
    if w >= h {
        sum += refs.above[..w].iter().sum::<i32>();
    }
    if w <= h {
        sum += refs.left[..h].iter().sum::<i32>();
    }
    let dc = (sum + div_offset) >> div_shift;
    vec![dc; w * h]
}

/// Position-dependent prediction combination for planar/DC
/// (VTM `IntraPrediction.cpp:248-262` PDPC step).
pub fn apply_pdpc(pred: &mut [i32], refs: &RefSamples, w: usize, h: usize) {
    let log2w = log2_exact(w);
    let log2h = log2_exact(h);
    let scale = ((log2w + log2h).saturating_sub(2)) >> 2;
    for y in 0..h {
        let wt = 32i32 >> ((y as u32 * 2) >> scale).min(31);
        let left = refs.left[y];
        for x in 0..w {
            let wl = 32i32 >> ((x as u32 * 2) >> scale).min(31);
            let top = refs.above[x];
            let val = pred[y * w + x];
            pred[y * w + x] = val + ((wl * (left - val) + wt * (top - val) + 32) >> 6);
        }
    }
}

/// Directional angular intra prediction for modes `2..=66` (including wide-angle
/// remapping, MRL reference line offsets, 4-tap cubic/Gaussian luma filtering,
/// 2-tap linear chroma filtering, and angular PDPC).
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.12 & §8.4.5.2.14;
/// VTM `IntraPrediction.cpp:455-639` (`xPredIntraAng`).
pub fn predict_angular_with_params(
    mrl_refs: &MrlRefSamples,
    w: usize,
    h: usize,
    is_luma: bool,
    params: &AngularParams,
) -> Vec<i32> {
    let is_mode_ver = params.is_mode_ver;
    let multi_ref_idx = if is_luma { mrl_refs.mrl_idx } else { 0 };
    let intra_pred_angle = params.intra_pred_angle;
    let abs_inv_angle = params.abs_inv_angle;

    let top_ref_len = 2 * w;
    let left_ref_len = 2 * h;

    let base_offset = h.max(w) + 4;
    let buf_len = base_offset + 2 * w.max(h) + 64;
    let mut ref_above = vec![128i32; buf_len];
    let mut ref_left = vec![128i32; buf_len];

    let main_base: usize;
    let side_base: usize;

    if intra_pred_angle < 0 {
        for x in 0..=(w + 1 + multi_ref_idx) {
            ref_above[base_offset + x] = mrl_refs.row_above[x.min(mrl_refs.row_above.len() - 1)];
        }
        for y in 0..=(h + 1 + multi_ref_idx) {
            ref_left[base_offset + y] = mrl_refs.row_left[y.min(mrl_refs.row_left.len() - 1)];
        }
        main_base = base_offset + multi_ref_idx;
        side_base = base_offset + multi_ref_idx;

        let size_side = if is_mode_ver { h as i32 } else { w as i32 };
        for k in -size_side..=-1 {
            let proj = ((-k * abs_inv_angle + 256) >> 9).min(size_side) as usize;
            let dst_idx = (base_offset as isize + k as isize) as usize;
            if is_mode_ver {
                ref_above[dst_idx] = ref_left[base_offset + proj];
            } else {
                ref_left[dst_idx] = ref_above[base_offset + proj];
            }
        }
    } else {
        for x in 0..=(top_ref_len + multi_ref_idx) {
            ref_above[base_offset + x] = mrl_refs.row_above[x.min(mrl_refs.row_above.len() - 1)];
        }
        for y in 0..=(left_ref_len + multi_ref_idx) {
            ref_left[base_offset + y] = mrl_refs.row_left[y.min(mrl_refs.row_left.len() - 1)];
        }
        let log2_ratio = floor_log2_u32(w as u32) - floor_log2_u32(h as u32);
        let s = 0.max(if is_mode_ver { log2_ratio } else { -log2_ratio }) as usize;
        let max_index = (multi_ref_idx << s) + 2;
        let ref_length = if is_mode_ver {
            top_ref_len
        } else {
            left_ref_len
        };
        if is_mode_ver {
            let val = ref_above[base_offset + ref_length + multi_ref_idx];
            for z in 1..=max_index {
                ref_above[base_offset + ref_length + multi_ref_idx + z] = val;
            }
        } else {
            let val = ref_left[base_offset + ref_length + multi_ref_idx];
            for z in 1..=max_index {
                ref_left[base_offset + ref_length + multi_ref_idx + z] = val;
            }
        }
        main_base = base_offset + multi_ref_idx;
        side_base = base_offset + multi_ref_idx;
    }

    let (ref_main, ref_side) = if is_mode_ver {
        (&ref_above, &ref_left)
    } else {
        (&ref_left, &ref_above)
    };

    let (work_w, work_h) = if is_mode_ver { (w, h) } else { (h, w) };
    let mut temp_buf = vec![0i32; work_w * work_h];

    if intra_pred_angle == 0 {
        let scale = (floor_log2_u32(work_w as u32) + floor_log2_u32(work_h as u32) - 2) >> 2;
        let top_left = ref_main[main_base];
        for y in 0..work_h {
            let row_off = y * work_w;
            for x in 0..work_w {
                temp_buf[row_off + x] = ref_main[main_base + x + 1];
            }
            if params.apply_pdpc && scale >= 0 {
                let left = ref_side[side_base + 1 + y];
                let limit = ((3usize) << (scale as usize)).min(work_w);
                for x in 0..limit {
                    let wl = 32i32 >> ((2 * x) >> (scale as usize));
                    let val = temp_buf[row_off + x];
                    temp_buf[row_off + x] =
                        (val + ((wl * (left - top_left) + 32) >> 6)).clamp(0, 255);
                }
            }
        }
    } else {
        let int_slope = is_integer_slope(intra_pred_angle.abs());
        let mut delta_pos = intra_pred_angle * (1 + multi_ref_idx as i32);
        for y in 0..work_h {
            let row_off = y * work_w;
            let delta_int = delta_pos >> 5;
            let delta_fract = (delta_pos & 31) as usize;

            if !int_slope {
                if is_luma {
                    let gauss: [i32; 4] = [
                        16 - (delta_fract as i32 >> 1),
                        32 - (delta_fract as i32 >> 1),
                        16 + (delta_fract as i32 >> 1),
                        delta_fract as i32 >> 1,
                    ];
                    let f = if !params.interpolation_flag {
                        &CHROMA_FILTER_4TAP[delta_fract]
                    } else {
                        &gauss
                    };
                    for x in 0..work_w {
                        let base_idx =
                            (main_base as isize + delta_int as isize + x as isize) as usize;
                        let p0 = ref_main[base_idx];
                        let p1 = ref_main[base_idx + 1];
                        let p2 = ref_main[base_idx + 2];
                        let p3 = ref_main[base_idx + 3];
                        let val = (f[0] * p0 + f[1] * p1 + f[2] * p2 + f[3] * p3 + 32) >> 6;
                        temp_buf[row_off + x] = val.clamp(0, 255);
                    }
                } else {
                    for x in 0..work_w {
                        let base_idx =
                            (main_base as isize + delta_int as isize + x as isize + 1) as usize;
                        let p0 = ref_main[base_idx];
                        let p1 = ref_main[base_idx + 1];
                        temp_buf[row_off + x] = p0 + (((delta_fract as i32) * (p1 - p0) + 16) >> 5);
                    }
                }
            } else {
                for x in 0..work_w {
                    let idx = (main_base as isize + delta_int as isize + x as isize + 1) as usize;
                    temp_buf[row_off + x] = ref_main[idx];
                }
            }

            if params.apply_pdpc {
                let scale = params.angular_scale.max(0) as usize;
                let mut inv_angle_sum = 256i32;
                let limit = ((3usize) << scale).min(work_w);
                for x in 0..limit {
                    inv_angle_sum += abs_inv_angle;
                    let wl = 32i32 >> ((2 * x) >> scale);
                    let left_idx = side_base + y + ((inv_angle_sum >> 9) as usize) + 1;
                    let left = ref_side[left_idx.min(ref_side.len() - 1)];
                    let val = temp_buf[row_off + x];
                    temp_buf[row_off + x] = (val + ((wl * (left - val) + 32) >> 6)).clamp(0, 255);
                }
            }

            delta_pos += intra_pred_angle;
        }
    }

    if is_mode_ver {
        temp_buf
    } else {
        let mut dst = vec![0i32; w * h];
        for y in 0..work_h {
            for x in 0..work_w {
                dst[x * w + y] = temp_buf[y * work_w + x];
            }
        }
        dst
    }
}

/// Predict a `w x h` block using directional angular mode `dir_mode` (`2..=66`)
/// on standard (`mrl_idx == 0`) reference samples.
pub fn predict_angular(
    refs: &RefSamples,
    w: usize,
    h: usize,
    is_luma: bool,
    dir_mode: u8,
) -> Vec<i32> {
    let params = init_angular_params(dir_mode, w, h, w, h, is_luma, 0, false);
    let used_refs = if params.ref_filter_flag {
        refs.filtered()
    } else {
        refs.clone()
    };
    let mrl_refs = MrlRefSamples::from_ref_samples(&used_refs);
    predict_angular_with_params(&mrl_refs, w, h, is_luma, &params)
}

/// Block DPCM intra prediction (`IntraPrediction.cpp:641-676`, `xPredIntraBDPCM`).
pub fn predict_bdpcm(refs: &RefSamples, w: usize, h: usize, vertical: bool) -> Vec<i32> {
    let mut pred = vec![0i32; w * h];
    if vertical {
        for y in 0..h {
            for x in 0..w {
                pred[y * w + x] = refs.above[x];
            }
        }
    } else {
        for y in 0..h {
            let val = refs.left[y];
            for x in 0..w {
                pred[y * w + x] = val;
            }
        }
    }
    pred
}

/// Intra Sub-Partitions (ISP) split mode (H.266 §8.4.5.1, VTM `UnitTools.cpp:445-549`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum IspMode {
    /// No ISP split (`intra_subpartitions_mode_flag == 0`).
    #[default]
    None,
    /// Horizontal split into 2 or 4 row sub-partitions (`ISPType::HOR`).
    Hor,
    /// Vertical split into 2 or 4 column sub-partitions (`ISPType::VER`).
    Ver,
}

/// Check if a luma CU of size `(w, h)` can use ISP (`UnitTools.cpp:486-495`).
pub fn can_use_isp(w: usize, h: usize, max_tb_size: usize) -> bool {
    if w < 4 || h < 4 || w > max_tb_size || h > max_tb_size {
        return false;
    }
    w * h > 16
}

/// Compute the sub-partition dimension along the split axis for ISP (`UnitTools.cpp:520-549`).
pub fn isp_split_dim(w: usize, h: usize, isp_mode: IspMode) -> usize {
    let (split_dim, non_split_dim) = match isp_mode {
        IspMode::Hor => (h, w),
        IspMode::Ver => (w, h),
        IspMode::None => return 0,
    };
    let min_samples = 16usize;
    let factor = if non_split_dim < min_samples {
        min_samples >> log2_exact(non_split_dim)
    } else {
        1
    };
    (split_dim >> 2).max(factor)
}

/// Return the list of `(sub_bx, sub_by, sub_w, sub_h)` sub-partitions for a CU using ISP.
pub fn isp_subpartitions(
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    isp_mode: IspMode,
) -> Vec<(usize, usize, usize, usize)> {
    match isp_mode {
        IspMode::None => vec![(bx, by, w, h)],
        IspMode::Hor => {
            let sub_h = isp_split_dim(w, h, IspMode::Hor).max(1);
            let count = h / sub_h;
            (0..count).map(|i| (bx, by + i * sub_h, w, sub_h)).collect()
        }
        IspMode::Ver => {
            let sub_w = isp_split_dim(w, h, IspMode::Ver).max(1);
            let count = w / sub_w;
            (0..count).map(|i| (bx + i * sub_w, by, sub_w, h)).collect()
        }
    }
}

/// Linear model parameters `pred_C(x, y) = ((a * rec_L(x, y)) >> shift) + b`
/// for Cross-Component Linear Model (CCLM) prediction.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CclmParams {
    /// Multiplier `a`.
    pub a: i32,
    /// Offset `b`.
    pub b: i32,
    /// Right shift `k` (`shift`).
    pub shift: u32,
}

/// Derive CCLM linear model parameters `(a, b, shift)` from up to 4 selected
/// `(luma, chroma)` template reference pairs.
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.13 Equations 289–307 & Table 30
/// (PDF pp. 277–279); VTM `IntraPrediction.cpp:1748-1823` (`xGetLMParameters`).
pub fn derive_cclm_params_from_4_samples(
    mut select_luma: [i32; 4],
    mut select_chroma: [i32; 4],
    cnt: usize,
    bit_depth: u8,
) -> CclmParams {
    if cnt == 0 {
        return CclmParams {
            a: 0,
            b: 1i32 << (bit_depth.saturating_sub(1)),
            shift: 0,
        };
    }
    if cnt == 2 {
        select_luma[3] = select_luma[0];
        select_chroma[3] = select_chroma[0];
        select_luma[2] = select_luma[1];
        select_chroma[2] = select_chroma[1];
        select_luma[0] = select_luma[1];
        select_chroma[0] = select_chroma[1];
        select_luma[1] = select_luma[3];
        select_chroma[1] = select_chroma[3];
    }

    let mut min_grp = [0usize, 2usize];
    let mut max_grp = [1usize, 3usize];
    if select_luma[min_grp[0]] > select_luma[min_grp[1]] {
        min_grp.swap(0, 1);
    }
    if select_luma[max_grp[0]] > select_luma[max_grp[1]] {
        max_grp.swap(0, 1);
    }
    if select_luma[min_grp[0]] > select_luma[max_grp[1]] {
        core::mem::swap(&mut min_grp, &mut max_grp);
    }
    if select_luma[min_grp[1]] > select_luma[max_grp[0]] {
        core::mem::swap(&mut min_grp[1], &mut max_grp[0]);
    }

    let min_luma = (select_luma[min_grp[0]] + select_luma[min_grp[1]] + 1) >> 1;
    let min_chroma = (select_chroma[min_grp[0]] + select_chroma[min_grp[1]] + 1) >> 1;
    let max_luma = (select_luma[max_grp[0]] + select_luma[max_grp[1]] + 1) >> 1;
    let max_chroma = (select_chroma[max_grp[0]] + select_chroma[max_grp[1]] + 1) >> 1;

    let diff = max_luma - min_luma;
    if diff > 0 {
        let diff_c = max_chroma - min_chroma;
        let mut x = floor_log2_u32(diff as u32);
        let norm_diff = ((diff << 4) >> x) & 15;
        let v = i32::from(CCLM_DIV_SIG_TABLE[norm_diff as usize]) | 8;
        if norm_diff != 0 {
            x += 1;
        }
        let y = if diff_c == 0 {
            1
        } else {
            floor_log2_u32(diff_c.unsigned_abs()) + 1
        };
        let add = (1i32 << y) >> 1;
        let mut a = (diff_c * v + add) >> y;
        let mut shift = 3 + x - y;
        if shift < 1 {
            shift = 1;
            a = if a == 0 {
                0
            } else if a < 0 {
                -15
            } else {
                15
            };
        }
        let b = min_chroma - ((a * min_luma) >> shift);
        CclmParams {
            a,
            b,
            shift: shift as u32,
        }
    } else {
        CclmParams {
            a: 0,
            b: min_chroma,
            shift: 0,
        }
    }
}

/// Downsample a 4:2:0 reconstructed luma region `(2 * cw) x (2 * ch)` at luma
/// position `(lx, ly)` using the normative `[1, 2, 1; 1, 2, 1] / 8` filter
/// (or `[1, 2, 1] / 4` on the top CTU boundary row).
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.13 Equations 261–275;
/// VTM `IntraPrediction.cpp:1545-1594` (`xGetLumaRecPixels`).
pub fn downsample_luma_for_cclm_420(
    luma_recon: &Plane,
    lx: usize,
    ly: usize,
    cw: usize,
    ch: usize,
    left_available: bool,
) -> Vec<i32> {
    let mut ds = vec![0i32; cw * ch];
    for j in 0..ch {
        let y0 = (ly + 2 * j).min(luma_recon.height - 1);
        let y1 = (ly + 2 * j + 1).min(luma_recon.height - 1);
        for i in 0..cw {
            let x0 = (lx + 2 * i).min(luma_recon.width - 1);
            let x_right = (lx + 2 * i + 1).min(luma_recon.width - 1);
            let left_pad = i == 0 && !left_available;
            let x_left = if left_pad || x0 == 0 { x0 } else { x0 - 1 };

            let s = 4
                + i32::from(luma_recon.get(x0, y0)) * 2
                + i32::from(luma_recon.get(x_right, y0))
                + i32::from(luma_recon.get(x_left, y0))
                + i32::from(luma_recon.get(x0, y1)) * 2
                + i32::from(luma_recon.get(x_right, y1))
                + i32::from(luma_recon.get(x_left, y1));
            ds[j * cw + i] = s >> 3;
        }
    }
    ds
}

/// Predict a 4:2:0 chroma block `(cw x ch)` at chroma coordinates `(cx, cy)` using
/// Cross-Component Linear Model (`LM_CHROMA_IDX = 67`, `MDLM_L_IDX = 68`, or `MDLM_T_IDX = 69`).
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.13;
/// VTM `IntraPrediction.cpp:266-288, 1327-1823`.
pub fn predict_cclm(
    luma_recon: &Plane,
    chroma_recon: &Plane,
    cx: usize,
    cy: usize,
    cw: usize,
    ch: usize,
    cclm_mode: u8,
    ctu_size_luma: usize,
) -> Vec<i32> {
    let lx = cx * 2;
    let ly = cy * 2;
    let mut above_avail = cy > 0;
    let mut left_avail = cx > 0;
    let is_first_row_of_ctu = ctu_size_luma > 0 && (ly & (ctu_size_luma - 1)) == 0;

    let mut top_template_len = cw;
    let mut left_template_len = ch;
    if cclm_mode == MDLM_T_IDX {
        left_avail = false;
        let max_ext = cw.min(ch);
        let avail_ext = (chroma_recon.width.saturating_sub(cx + cw)).min(max_ext);
        top_template_len = cw + avail_ext;
    } else if cclm_mode == MDLM_L_IDX {
        above_avail = false;
        left_template_len = ch;
    }

    let mut luma_top = vec![128i32; top_template_len];
    let mut chroma_top = vec![128i32; top_template_len];
    if above_avail {
        for i in 0..top_template_len {
            let x_c = (cx + i).min(chroma_recon.width - 1);
            chroma_top[i] = i32::from(chroma_recon.get(x_c, cy - 1));

            let x0 = (lx + 2 * i).min(luma_recon.width - 1);
            let x_r = (lx + 2 * i + 1).min(luma_recon.width - 1);
            let left_pad = i == 0 && !left_avail;
            let x_l = if left_pad || x0 == 0 { x0 } else { x0 - 1 };

            if is_first_row_of_ctu || ly < 2 {
                let y_src = ly.saturating_sub(1);
                luma_top[i] = (i32::from(luma_recon.get(x0, y_src)) * 2
                    + i32::from(luma_recon.get(x_l, y_src))
                    + i32::from(luma_recon.get(x_r, y_src))
                    + 2)
                    >> 2;
            } else {
                let y0 = ly - 2;
                let y1 = ly - 1;
                let s = 4
                    + i32::from(luma_recon.get(x0, y0)) * 2
                    + i32::from(luma_recon.get(x_r, y0))
                    + i32::from(luma_recon.get(x_l, y0))
                    + i32::from(luma_recon.get(x0, y1)) * 2
                    + i32::from(luma_recon.get(x_r, y1))
                    + i32::from(luma_recon.get(x_l, y1));
                luma_top[i] = s >> 3;
            }
        }
    }

    let mut luma_left = vec![128i32; left_template_len];
    let mut chroma_left = vec![128i32; left_template_len];
    if left_avail {
        for j in 0..left_template_len {
            let y_c = (cy + j).min(chroma_recon.height - 1);
            chroma_left[j] = i32::from(chroma_recon.get(cx - 1, y_c));

            let y0 = (ly + 2 * j).min(luma_recon.height - 1);
            let y1 = (ly + 2 * j + 1).min(luma_recon.height - 1);
            let x0 = lx.saturating_sub(2);
            let x_r = (x0 + 1).min(luma_recon.width - 1);
            let x_l = x0.saturating_sub(1);
            let s = 4
                + i32::from(luma_recon.get(x0, y0)) * 2
                + i32::from(luma_recon.get(x_r, y0))
                + i32::from(luma_recon.get(x_l, y0))
                + i32::from(luma_recon.get(x0, y1)) * 2
                + i32::from(luma_recon.get(x_r, y1))
                + i32::from(luma_recon.get(x_l, y1));
            luma_left[j] = s >> 3;
        }
    }

    let above_is_4 = if left_avail { 0usize } else { 1usize };
    let left_is_4 = if above_avail { 0usize } else { 1usize };

    let start_above = top_template_len >> (2 + above_is_4);
    let step_above = 1.max(top_template_len >> (1 + above_is_4));
    let start_left = left_template_len >> (2 + left_is_4);
    let step_left = 1.max(left_template_len >> (1 + left_is_4));

    let mut select_luma = [0i32; 4];
    let mut select_chroma = [0i32; 4];
    let mut cnt_t = 0usize;
    let mut cnt_l = 0usize;

    if above_avail {
        cnt_t = top_template_len.min((1 + above_is_4) << 1);
        let mut pos = start_above;
        for c in 0..cnt_t {
            select_luma[c] = luma_top[pos.min(top_template_len - 1)];
            select_chroma[c] = chroma_top[pos.min(top_template_len - 1)];
            pos += step_above;
        }
    }
    if left_avail {
        cnt_l = left_template_len.min((1 + left_is_4) << 1);
        let mut pos = start_left;
        for c in 0..cnt_l {
            select_luma[cnt_t + c] = luma_left[pos.min(left_template_len - 1)];
            select_chroma[cnt_t + c] = chroma_left[pos.min(left_template_len - 1)];
            pos += step_left;
        }
    }

    let params = derive_cclm_params_from_4_samples(select_luma, select_chroma, cnt_t + cnt_l, 8);
    let ds_luma = downsample_luma_for_cclm_420(luma_recon, lx, ly, cw, ch, cx > 0);

    ds_luma
        .into_iter()
        .map(|y_val| (((y_val * params.a) >> params.shift) + params.b).clamp(0, 255))
        .collect()
}

/// Matrix-based Intra Prediction (MIP) size class (`MipSizeId`, H.266 §8.4.5.2.1,
/// VTM `MatrixIntraPrediction.cpp:140-170`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MipSizeId {
    /// `4x4` block (`16` MIP modes, reduced boundary `2+2=4`, reduced pred `4x4`).
    S0,
    /// `4xN`, `Nx4`, or `8x8` block (`8` MIP modes, reduced boundary `4+4=8`, reduced pred `4x4`).
    S1,
    /// All other blocks with `w >= 8 && h >= 8` (`6` MIP modes, reduced boundary `4+4=8`, reduced pred `8x8`).
    S2,
}

/// Determine the MIP size class for a block of dimensions `(w, h)`.
pub fn get_mip_size_id(w: usize, h: usize) -> MipSizeId {
    if w == 4 && h == 4 {
        MipSizeId::S0
    } else if w == 4 || h == 4 || (w == 8 && h == 8) {
        MipSizeId::S1
    } else {
        MipSizeId::S2
    }
}

/// Return the number of MIP modes (`16`, `8`, or `6`) for a block of size `(w, h)`.
pub fn get_num_modes_mip(w: usize, h: usize) -> usize {
    match get_mip_size_id(w, h) {
        MipSizeId::S0 => 16,
        MipSizeId::S1 => 8,
        MipSizeId::S2 => 6,
    }
}

fn mip_boundary_downsampling_1d(full_src: &[i32], src_len: usize, dst_len: usize) -> Vec<i32> {
    if dst_len < src_len {
        let downsmp_factor = src_len / dst_len;
        let log2_factor = log2_exact(downsmp_factor);
        let rounding_offset = 1i32 << (log2_factor - 1);
        let mut reduced = vec![0i32; dst_len];
        for (dst_idx, slot) in reduced.iter_mut().enumerate() {
            let sum: i32 = full_src[dst_idx * downsmp_factor..(dst_idx + 1) * downsmp_factor]
                .iter()
                .sum();
            *slot = (sum + rounding_offset) >> log2_factor;
        }
        reduced
    } else {
        full_src[..dst_len].to_vec()
    }
}

#[allow(clippy::too_many_arguments)]
fn mip_prediction_upsampling_1d(
    dst: &mut [i32],
    dst_base: usize,
    src: &[i32],
    src_base: usize,
    bndry: &[i32],
    src_size_upsmp_dim: usize,
    src_size_orth_dim: usize,
    src_step: usize,
    src_stride: usize,
    dst_step: usize,
    dst_stride: usize,
    bndry_step: usize,
    upsmp_factor: usize,
) {
    let log2_factor = log2_exact(upsmp_factor);
    let rounding_offset = 1i32 << (log2_factor - 1);

    for idx_orth in 0..src_size_orth_dim {
        let src_line = src_base + idx_orth * src_stride;
        let dst_line = dst_base + idx_orth * dst_stride;
        let mut before_val = bndry[idx_orth * bndry_step + bndry_step - 1];
        for idx_upsmp in 0..src_size_upsmp_dim {
            let behind_val = src[src_line + idx_upsmp * src_step];
            let mut scaled_before = before_val << log2_factor;
            let mut scaled_behind = 0i32;
            let mut curr_dst = dst_line + idx_upsmp * upsmp_factor * dst_step;
            for _pos in 1..=upsmp_factor {
                scaled_before -= before_val;
                scaled_behind += behind_val;
                dst[curr_dst] = (scaled_before + scaled_behind + rounding_offset) >> log2_factor;
                curr_dst += dst_step;
            }
            before_val = behind_val;
        }
    }
}

/// Predict a `w x h` block using Matrix-based Intra Prediction (MIP).
///
/// Normative source: ITU-T Rec. H.266 §8.4.5.2.1–§8.4.5.2.4 (PDF pp. 256–263);
/// VTM `MatrixIntraPrediction.cpp:61-370` & `MipData.h:38-882`.
pub fn predict_mip(
    refs: &RefSamples,
    w: usize,
    h: usize,
    mode_idx: u8,
    transpose: bool,
) -> Vec<i32> {
    predict_mip_bd(refs, w, h, mode_idx, transpose, 8)
}

/// [`predict_mip`] parameterised by sample bit depth.
///
/// The rebasing centre `1 << (BitDepth - 1)` and the output clip
/// `ClipBD(., BitDepth)` both depend on the picture bit depth
/// (ITU-T Rec. H.266 §8.4.5.2.11; VTM `MatrixIntraPrediction.cpp:110,352`).
fn predict_mip_bd(
    refs: &RefSamples,
    w: usize,
    h: usize,
    mode_idx: u8,
    transpose: bool,
    bit_depth: u8,
) -> Vec<i32> {
    let size_id = get_mip_size_id(w, h);
    let reduced_bdry_size = if size_id == MipSizeId::S0 { 2 } else { 4 };
    let reduced_pred_size = if size_id == MipSizeId::S2 { 8 } else { 4 };
    let upsmp_hor = w / reduced_pred_size;
    let upsmp_ver = h / reduced_pred_size;

    let ref_top = &refs.above[..w];
    let ref_left = &refs.left[..h];

    let top_reduced = mip_boundary_downsampling_1d(ref_top, w, reduced_bdry_size);
    let left_reduced = mip_boundary_downsampling_1d(ref_left, h, reduced_bdry_size);

    let input_size = 2 * reduced_bdry_size;
    let mut reduced_bdry = Vec::with_capacity(input_size);
    if transpose {
        reduced_bdry.extend_from_slice(&left_reduced);
        reduced_bdry.extend_from_slice(&top_reduced);
    } else {
        reduced_bdry.extend_from_slice(&top_reduced);
        reduced_bdry.extend_from_slice(&left_reduced);
    }

    let input_offset = reduced_bdry[0];
    let has_first_col = size_id != MipSizeId::S2;
    let centre = 1i32 << (bit_depth.clamp(8, 12) - 1);
    let max_value = (1i32 << bit_depth.clamp(8, 12)) - 1;
    reduced_bdry[0] = if has_first_col {
        centre - input_offset
    } else {
        0
    };
    for v in reduced_bdry.iter_mut().skip(1) {
        *v -= input_offset;
    }

    let sum_input: i32 = reduced_bdry.iter().sum();
    let offset = (1i32 << (MIP_SHIFT_MATRIX - 1)) - MIP_OFFSET_MATRIX * sum_input;

    let num_pred = reduced_pred_size * reduced_pred_size;
    let mut res_raw = vec![0i32; num_pred];
    let m_idx = (mode_idx as usize) % get_num_modes_mip(w, h);

    for pos in 0..num_pred {
        let dot: i32 = match size_id {
            MipSizeId::S0 => {
                let row = &MIP_MATRIX_4X4[m_idx][pos];
                (0..4).map(|i| reduced_bdry[i] * i32::from(row[i])).sum()
            }
            MipSizeId::S1 => {
                let row = &MIP_MATRIX_8X8[m_idx][pos];
                (0..8).map(|i| reduced_bdry[i] * i32::from(row[i])).sum()
            }
            MipSizeId::S2 => {
                let row = &MIP_MATRIX_16X16[m_idx][pos];
                (0..7)
                    .map(|i| reduced_bdry[i + 1] * i32::from(row[i]))
                    .sum()
            }
        };
        res_raw[pos] = (((dot + offset) >> MIP_SHIFT_MATRIX) + input_offset).clamp(0, max_value);
    }

    let reduced_pred = if transpose {
        let mut tr = vec![0i32; num_pred];
        for y in 0..reduced_pred_size {
            for x in 0..reduced_pred_size {
                tr[y * reduced_pred_size + x] = res_raw[x * reduced_pred_size + y];
            }
        }
        tr
    } else {
        res_raw
    };

    if upsmp_hor == 1 && upsmp_ver == 1 {
        return reduced_pred;
    }

    let mut dst = vec![0i32; w * h];
    if upsmp_hor > 1 && upsmp_ver == 1 {
        mip_prediction_upsampling_1d(
            &mut dst,
            0,
            &reduced_pred,
            0,
            ref_left,
            reduced_pred_size,
            reduced_pred_size,
            1,
            reduced_pred_size,
            1,
            w,
            1,
            upsmp_hor,
        );
    } else if upsmp_hor == 1 && upsmp_ver > 1 {
        mip_prediction_upsampling_1d(
            &mut dst,
            0,
            &reduced_pred,
            0,
            ref_top,
            reduced_pred_size,
            w,
            w,
            1,
            w,
            1,
            1,
            upsmp_ver,
        );
    } else {
        let hor_dst_base = (upsmp_ver - 1) * w;
        let ver_src_step = w * upsmp_ver;
        mip_prediction_upsampling_1d(
            &mut dst,
            hor_dst_base,
            &reduced_pred,
            0,
            ref_left,
            reduced_pred_size,
            reduced_pred_size,
            1,
            reduced_pred_size,
            1,
            ver_src_step,
            upsmp_ver,
            upsmp_hor,
        );
        let temp_hor = dst.clone();
        mip_prediction_upsampling_1d(
            &mut dst,
            0,
            &temp_hor,
            hor_dst_base,
            ref_top,
            reduced_pred_size,
            w,
            ver_src_step,
            1,
            w,
            1,
            1,
            upsmp_ver,
        );
    }
    dst
}

/// Produce the prediction block for one component (baseline `IntraMode` API).
pub fn predict_block(
    recon: &Plane,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    is_luma: bool,
    mode: IntraMode,
) -> Vec<i32> {
    let refs = gather_references(recon, bx, by, w, h);
    match mode {
        // `predict_angular` selects and applies the `[1 2 1] / 4` reference filter
        // (`refFilterFlag`, H.266 §8.4.5.2.10) and the angular PDPC post-filter
        // (§8.4.5.2.14) from the same `AngularParams`; pre-filtering or applying
        // PDPC again here would apply both twice.
        IntraMode::Angular(dir) => predict_angular(&refs, w, h, is_luma, dir),
        IntraMode::Planar | IntraMode::Dc => {
            let used_refs = if uses_reference_filter(is_luma, mode, w, h) {
                refs.filtered()
            } else {
                refs
            };
            let mut pred = if mode == IntraMode::Planar {
                predict_planar(&used_refs, w, h)
            } else {
                predict_dc(&used_refs, w, h)
            };
            apply_pdpc(&mut pred, &used_refs, w, h);
            pred
        }
    }
}

/// Produce the prediction block for any full `IntraPredMode` (Planar, DC, Angular 2..=66,
/// MRL, MIP, BDPCM, or CCLM).
#[allow(clippy::too_many_arguments)]
pub fn predict_block_full(
    recon: &Plane,
    luma_recon: Option<&Plane>,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    is_luma: bool,
    mode: IntraPredMode,
    mrl_idx: usize,
    ctu_size: usize,
) -> Vec<i32> {
    match mode {
        IntraPredMode::Planar => predict_block(recon, bx, by, w, h, is_luma, IntraMode::Planar),
        IntraPredMode::Dc => predict_block(recon, bx, by, w, h, is_luma, IntraMode::Dc),
        IntraPredMode::Angular(dir) => {
            if mrl_idx == 0 {
                let refs = gather_references(recon, bx, by, w, h);
                predict_angular(&refs, w, h, is_luma, dir)
            } else {
                let mrl_refs = gather_references_mrl(recon, bx, by, w, h, mrl_idx, ctu_size);
                let params = init_angular_params(dir, w, h, w, h, is_luma, mrl_refs.mrl_idx, false);
                predict_angular_with_params(&mrl_refs, w, h, is_luma, &params)
            }
        }
        IntraPredMode::LmChroma | IntraPredMode::MdlmL | IntraPredMode::MdlmT => {
            if let Some(y_plane) = luma_recon {
                predict_cclm(y_plane, recon, bx, by, w, h, mode.mode_index(), ctu_size)
            } else {
                predict_block(recon, bx, by, w, h, false, IntraMode::Planar)
            }
        }
        IntraPredMode::Mip {
            mode_idx,
            transposed,
        } => {
            let refs = gather_references(recon, bx, by, w, h);
            predict_mip(&refs, w, h, mode_idx, transposed)
        }
        IntraPredMode::Bdpcm { vertical } => {
            let refs = gather_references(recon, bx, by, w, h);
            predict_bdpcm(&refs, w, h, vertical)
        }
    }
}

/// Choose between PLANAR and DC for one block.
///
/// Both predictions are produced from the current reconstruction, then compared
/// with the source block by sum of absolute differences. DC is selected only
/// when its SAD is strictly lower, so PLANAR wins ties.
pub fn choose_intra_mode(
    recon: &Plane,
    src: &Plane,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    is_luma: bool,
) -> IntraMode {
    let sad = |mode: IntraMode| -> u64 {
        let pred = predict_block(recon, bx, by, w, h, is_luma, mode);
        let mut total = 0u64;
        for y in 0..h {
            for x in 0..w {
                let idx = y * w + x;
                let source = i32::from(src.get(bx + x, by + y));
                total += u64::from((source - pred[idx]).unsigned_abs());
            }
        }
        total
    };
    if sad(IntraMode::Dc) < sad(IntraMode::Planar) {
        IntraMode::Dc
    } else {
        IntraMode::Planar
    }
}

/// Choose the lowest-SAD luma intra prediction mode across Planar, DC, and the 65
/// directional angular modes (or the 6 MPM candidates when `mpm_only` is true).
#[allow(clippy::too_many_arguments)]
pub fn choose_luma_intra_pred_mode(
    recon: &Plane,
    src: &Plane,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    mpm: &[u8; 6],
    mpm_only: bool,
) -> IntraPredMode {
    let refs = gather_references(recon, bx, by, w, h);
    let refs_filtered = refs.filtered();

    let eval_sad = |pred: &[i32]| -> u64 {
        let mut total = 0u64;
        for y in 0..h {
            for x in 0..w {
                let source = i32::from(src.get(bx + x, by + y));
                total += u64::from((source - pred[y * w + x]).unsigned_abs());
            }
        }
        total
    };

    let mut best_mode = IntraPredMode::Planar;
    let mut best_cost = u64::MAX;

    let candidates: Vec<u8> = if mpm_only {
        mpm.to_vec()
    } else {
        (0..NUM_LUMA_MODE).collect()
    };

    for mode_idx in candidates {
        let pred = match mode_idx {
            PLANAR_IDX => {
                let used = if w * h > 32 { &refs_filtered } else { &refs };
                let mut p = predict_planar(used, w, h);
                apply_pdpc(&mut p, used, w, h);
                p
            }
            DC_IDX => {
                let mut p = predict_dc(&refs, w, h);
                apply_pdpc(&mut p, &refs, w, h);
                p
            }
            dir => {
                let params = init_angular_params(dir, w, h, w, h, true, 0, false);
                let used = if params.ref_filter_flag {
                    &refs_filtered
                } else {
                    &refs
                };
                let mrl = MrlRefSamples::from_ref_samples(used);
                predict_angular_with_params(&mrl, w, h, true, &params)
            }
        };
        let sad = eval_sad(&pred);
        if sad < best_cost {
            best_cost = sad;
            best_mode = IntraPredMode::from_mode_index(mode_idx).unwrap_or(IntraPredMode::Planar);
        }
    }
    best_mode
}

/// Normative H.266 chroma format indicator (`sps_chroma_format_idc`, ITU-T Rec. H.266
/// §6.2 Table 2, PDF p. 41).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum ChromaFormatIdc {
    /// Monochrome (`0`, `SubWidthC = 1, SubHeightC = 1`).
    Mono400 = 0,
    /// 4:2:0 (`1`, `SubWidthC = 2, SubHeightC = 2`).
    #[default]
    Chroma420 = 1,
    /// 4:2:2 (`2`, `SubWidthC = 2, SubHeightC = 1`).
    Chroma422 = 2,
    /// 4:4:4 (`3`, `SubWidthC = 1, SubHeightC = 1`).
    Chroma444 = 3,
}

impl ChromaFormatIdc {
    /// Convert a raw `sps_chroma_format_idc` value (`0..=3`) to [`ChromaFormatIdc`].
    #[inline]
    pub fn from_idc(idc: u8) -> Self {
        match idc {
            0 => Self::Mono400,
            2 => Self::Chroma422,
            3 => Self::Chroma444,
            _ => Self::Chroma420,
        }
    }

    /// Horizontal chroma subsampling factor `SubWidthC` (H.266 Table 2).
    #[inline]
    pub fn sub_width_c(self) -> usize {
        match self {
            Self::Chroma420 | Self::Chroma422 => 2,
            Self::Mono400 | Self::Chroma444 => 1,
        }
    }

    /// Vertical chroma subsampling factor `SubHeightC` (H.266 Table 2).
    #[inline]
    pub fn sub_height_c(self) -> usize {
        match self {
            Self::Chroma420 => 2,
            Self::Mono400 | Self::Chroma422 | Self::Chroma444 => 1,
        }
    }

    /// Number of active colour planes (`1` for `Mono400`, `3` for `4:2:0`/`4:2:2`/`4:4:4`).
    #[inline]
    pub fn num_planes(self) -> usize {
        match self {
            Self::Mono400 => 1,
            Self::Chroma420 | Self::Chroma422 | Self::Chroma444 => 3,
        }
    }

    /// True when chroma planes are present (`sps_chroma_format_idc != 0`).
    #[inline]
    pub fn is_chroma_enabled(self) -> bool {
        self != Self::Mono400
    }
}

/// 16-bit sample plane supporting 8-bit, 10-bit, and 12-bit H.266/VVC sample arrays.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Plane16 {
    /// Width of the plane in samples.
    pub width: usize,
    /// Height of the plane in samples.
    pub height: usize,
    /// Sample bit depth (`8..=12`).
    pub bit_depth: u8,
    /// Row-major sample buffer of length `width * height`.
    pub data: Vec<u16>,
}

impl Plane16 {
    /// Allocate a zero-initialised plane of `width x height` samples at `bit_depth`.
    pub fn new(width: usize, height: usize, bit_depth: u8) -> Self {
        Self {
            width,
            height,
            bit_depth: bit_depth.clamp(8, 12),
            data: vec![0u16; width * height],
        }
    }

    /// Construct a [`Plane16`] from a slice if `slice.len() == width * height`.
    pub fn from_slice(width: usize, height: usize, bit_depth: u8, slice: &[u16]) -> Option<Self> {
        if slice.len() != width * height {
            return None;
        }
        Some(Self {
            width,
            height,
            bit_depth: bit_depth.clamp(8, 12),
            data: slice.to_vec(),
        })
    }

    /// Convert an 8-bit [`Plane`] to a [`Plane16`], optionally shifting up to `target_bit_depth`.
    pub fn from_plane_8bit(plane: &Plane, target_bit_depth: u8) -> Self {
        let bd = target_bit_depth.clamp(8, 12);
        let shift = bd - 8;
        Self {
            width: plane.width,
            height: plane.height,
            bit_depth: bd,
            data: plane.data.iter().map(|&v| u16::from(v) << shift).collect(),
        }
    }

    /// Downconvert or extract an 8-bit [`Plane`] by shifting right by `bit_depth - 8`.
    pub fn to_plane_8bit(&self) -> Plane {
        let shift = self.bit_depth.saturating_sub(8);
        let add = if shift > 0 { 1u16 << (shift - 1) } else { 0 };
        Plane {
            width: self.width,
            height: self.height,
            data: self
                .data
                .iter()
                .map(|&v| ((v.saturating_add(add)) >> shift).min(255) as u8)
                .collect(),
        }
    }

    /// Maximum legal sample value `(1 << bit_depth) - 1`.
    #[inline]
    pub fn max_sample(&self) -> i32 {
        (1i32 << u32::from(self.bit_depth)) - 1
    }

    /// Read sample at `(x, y)`.
    #[inline]
    pub fn get(&self, x: usize, y: usize) -> u16 {
        self.data[y * self.width + x]
    }

    /// Write sample at `(x, y)`.
    #[inline]
    pub fn set(&mut self, x: usize, y: usize, val: u16) {
        let max_v = self.max_sample() as u16;
        self.data[y * self.width + x] = val.min(max_v);
    }
}

/// Neighbouring reference samples for 8/10/12-bit intra prediction (H.266 §8.4.5.2.2).
#[derive(Debug, Clone)]
pub struct ReferenceSamples16 {
    /// Top-left corner sample `p[-1][-1]`.
    pub top_left: u16,
    /// Above reference row `p[0 .. 2*width - 1][-1]`.
    pub above: Vec<u16>,
    /// Left reference column `p[-1][0 .. 2*height - 1]`.
    pub left: Vec<u16>,
    /// Sample bit depth (`8..=12`).
    pub bit_depth: u8,
}

impl ReferenceSamples16 {
    /// `[1 2 1]` smoothing of both reference rows (H.266 §8.4.5.2.10
    /// equations 325–329, VTM `IntraPrediction::xFilterReferenceSamples`).
    ///
    /// `p[-1][-1] = (p[-1][0] + 2*p[-1][-1] + p[0][-1] + 2) >> 2`; interior
    /// samples use their two neighbours; the outermost sample of each row is
    /// copied unchanged.
    #[allow(clippy::needless_range_loop)]
    pub fn filtered(&self) -> ReferenceSamples16 {
        let w2 = self.above.len();
        let h2 = self.left.len();
        let mut above = self.above.clone();
        let mut left = self.left.clone();

        let top_left =
            (2 * u32::from(self.top_left) + u32::from(self.above[0]) + u32::from(self.left[0]) + 2)
                >> 2;
        for j in 0..w2.saturating_sub(1) {
            let prev = if j == 0 {
                self.top_left
            } else {
                self.above[j - 1]
            };
            above[j] = ((u32::from(prev)
                + 2 * u32::from(self.above[j])
                + u32::from(self.above[j + 1])
                + 2)
                >> 2) as u16;
        }
        for j in 0..h2.saturating_sub(1) {
            let prev = if j == 0 {
                self.top_left
            } else {
                self.left[j - 1]
            };
            left[j] =
                ((u32::from(prev) + 2 * u32::from(self.left[j]) + u32::from(self.left[j + 1]) + 2)
                    >> 2) as u16;
        }
        ReferenceSamples16 {
            top_left: top_left as u16,
            above,
            left,
            bit_depth: self.bit_depth,
        }
    }
}

/// Gather and pad reference samples for a `(x, y, width, height)` block in a [`Plane16`]
/// (ITU-T Rec. H.266 §8.4.5.2.9, VTM `IntraPrediction::xFillReferenceSamples`).
///
/// Below-left samples (`p[-1][height..2*height-1]`) belong to blocks that have
/// not been reconstructed yet in raster order, so they are marked unavailable
/// and substituted with `p[-1][height-1]` (§8.4.5.2.9 step 2). Same rule as the
/// 8-bit [`gather_references`].
pub fn gather_references_16(
    plane: &Plane16,
    x: usize,
    y: usize,
    width: usize,
    height: usize,
) -> ReferenceSamples16 {
    let default_val = 1u16 << (plane.bit_depth.clamp(8, 12) - 1);
    let above_len = 2 * width;
    let left_len = 2 * height;
    let has_above = y > 0;
    let has_left = x > 0;

    let mut above = vec![default_val; above_len];
    let mut left = vec![default_val; left_len];

    if has_above {
        let avail_w = (plane.width.saturating_sub(x)).min(above_len);
        for i in 0..avail_w {
            above[i] = plane.get(x + i, y - 1);
        }
        let pad = above[avail_w.saturating_sub(1)];
        for item in above.iter_mut().skip(avail_w) {
            *item = pad;
        }
    }

    if has_left {
        let avail_h = (plane.height.saturating_sub(y)).min(height);
        for j in 0..avail_h {
            left[j] = plane.get(x - 1, y + j);
        }
        let pad = left[avail_h.saturating_sub(1)];
        for item in left.iter_mut().skip(avail_h) {
            *item = pad;
        }
    }

    if has_above && !has_left {
        left.fill(above[0]);
    } else if !has_above && has_left {
        above.fill(left[0]);
    }

    let top_left = if has_above && has_left {
        plane.get(x - 1, y - 1)
    } else if has_above {
        above[0]
    } else if has_left {
        left[0]
    } else {
        default_val
    };

    ReferenceSamples16 {
        top_left,
        above,
        left,
        bit_depth: plane.bit_depth,
    }
}

/// Predict a `(width, height)` block in a [`Plane16`] using `mode` (Planar, DC, or Angular `2..=66`).
pub fn predict_block_16(
    plane: &Plane16,
    x: usize,
    y: usize,
    width: usize,
    height: usize,
    is_luma: bool,
    mode: IntraPredMode,
) -> Vec<u16> {
    let refs = gather_references_16(plane, x, y, width, height);
    predict_from_refs_16(&refs, width, height, is_luma, mode)
}

/// Predict a `(width, height)` block with reference-availability substitution
/// driven by an already-reconstructed coding-unit map.
///
/// Above-right and below-left samples are only read when the coding unit that
/// contains them has already been reconstructed; otherwise the last available
/// sample of the reference row or column is propagated. `scale_x` and `scale_y`
/// map plane coordinates to the luma resolution of `is_coded` (they are `1` for
/// luma and the chroma subsampling factors for chroma).
#[allow(clippy::too_many_arguments)]
pub fn predict_coded_block_16<F>(
    plane: &Plane16,
    x: usize,
    y: usize,
    width: usize,
    height: usize,
    is_luma: bool,
    mode: IntraPredMode,
    scale_x: usize,
    scale_y: usize,
    is_coded: F,
) -> Vec<u16>
where
    F: Fn(usize, usize) -> bool,
{
    let mut refs = gather_references_16(plane, x, y, width, height);
    if y > 0 {
        let pad = refs.above[width - 1];
        for (i, sample) in refs.above.iter_mut().enumerate().skip(width) {
            let px = x + i;
            if px < plane.width && !is_coded(px * scale_x, (y - 1) * scale_y) {
                *sample = pad;
            }
        }
    }
    if x > 0 {
        for (j, sample) in refs.left.iter_mut().enumerate().skip(height) {
            let py = y + j;
            if py < plane.height && is_coded((x - 1) * scale_x, py * scale_y) {
                *sample = plane.get(x - 1, py);
            }
        }
    }
    predict_from_refs_16(&refs, width, height, is_luma, mode)
}

/// Shared prediction core for an already-gathered [`ReferenceSamples16`].
fn predict_from_refs_16(
    refs: &ReferenceSamples16,
    width: usize,
    height: usize,
    is_luma: bool,
    mode: IntraPredMode,
) -> Vec<u16> {
    let max_val = (1i32 << u32::from(refs.bit_depth.clamp(8, 12))) - 1;
    let log2_w = width.trailing_zeros();
    let log2_h = height.trailing_zeros();
    match mode {
        IntraPredMode::Planar => {
            // `filterFlag` for PLANAR: `refIdx == 0`, `nTbW * nTbH > 32`, luma,
            // no ISP split (H.266 §8.4.5.2.10, VTM `IntraPrediction.cpp:417-420`).
            let used_refs = if uses_reference_filter(is_luma, IntraMode::Planar, width, height) {
                refs.filtered()
            } else {
                refs.clone()
            };
            let mut out = vec![0u16; width * height];
            let shift = log2_w + log2_h + 1;
            let offset = 1i64 << (shift - 1);
            let tr = i64::from(used_refs.above[width]);
            let bl = i64::from(used_refs.left[height]);
            for ry in 0..height {
                let left = i64::from(used_refs.left[ry]);
                for rx in 0..width {
                    // H.266 §8.4.5.2.11 `predV`: above row and bottom-left corner.
                    let ver = (height - 1 - ry) as i64 * i64::from(used_refs.above[rx])
                        + (ry + 1) as i64 * bl;
                    // `predH`: left column and top-right corner.
                    let hor = (width - 1 - rx) as i64 * left + (rx + 1) as i64 * tr;
                    let val = ((ver << log2_w) + (hor << log2_h) + offset) >> shift;
                    out[ry * width + rx] = val.clamp(0, i64::from(max_val)) as u16;
                }
            }
            apply_pdpc_16(&mut out, &used_refs, width, height);
            out
        }
        IntraPredMode::Dc => {
            let sum_top: u32 = refs.above[..width].iter().map(|&v| u32::from(v)).sum();
            let sum_left: u32 = refs.left[..height].iter().map(|&v| u32::from(v)).sum();
            let dc = if width == height {
                ((sum_top + sum_left + width as u32) >> (log2_w + 1)) as u16
            } else if width > height {
                ((sum_top + (width as u32 >> 1)) >> log2_w) as u16
            } else {
                ((sum_left + (height as u32 >> 1)) >> log2_h) as u16
            };
            let mut out = vec![dc.min(max_val as u16); width * height];
            apply_pdpc_16(&mut out, refs, width, height);
            out
        }
        // `predict_angular_16` derives the reference-filter flag and the angular
        // PDPC parameters itself (H.266 §8.4.5.2.10, §8.4.5.2.14).
        IntraPredMode::Angular(dir) => predict_angular_16(refs, width, height, is_luma, dir),
        _ => vec![0u16; width * height],
    }
}

/// Position-dependent prediction combination for planar/DC on a [`Plane16`]
/// (H.266 §8.4.5.2.14, VTM `IntraPrediction.cpp:248-262`).
pub fn apply_pdpc_16(pred: &mut [u16], refs: &ReferenceSamples16, w: usize, h: usize) {
    let scale = ((log2_exact(w) + log2_exact(h)).saturating_sub(2)) >> 2;
    let max_val = (1i32 << u32::from(refs.bit_depth.clamp(8, 12))) - 1;
    for y in 0..h {
        let wt = 32i32 >> ((y as u32 * 2) >> scale).min(31);
        let left = i32::from(refs.left[y]);
        for x in 0..w {
            let wl = 32i32 >> ((x as u32 * 2) >> scale).min(31);
            let top = i32::from(refs.above[x]);
            let val = i32::from(pred[y * w + x]);
            pred[y * w + x] =
                (val + ((wl * (left - val) + wt * (top - val) + 32) >> 6)).clamp(0, max_val) as u16;
        }
    }
}

/// Normative 16-bit angular intra prediction with reference filtering,
/// 4-tap cubic/Gaussian (luma) or 2-tap linear (chroma) interpolation, and
/// angular PDPC (`H.266 §8.4.5.2.12`, §8.4.5.2.14, VTM `IntraPrediction.cpp`).
///
/// The reference filter is selected internally from the same
/// [`init_angular_params`] result used for prediction, so callers pass raw
/// reference samples.
pub fn predict_angular_16(
    refs: &ReferenceSamples16,
    width: usize,
    height: usize,
    is_luma: bool,
    mode_dir: u8,
) -> Vec<u16> {
    let bd = refs.bit_depth.clamp(8, 12);
    let max_val = (1i32 << u32::from(bd)) - 1;
    let default = 1i32 << (u32::from(bd) - 1);
    let params = init_angular_params(mode_dir, width, height, width, height, is_luma, 0, false);
    let used = if params.ref_filter_flag {
        refs.filtered()
    } else {
        refs.clone()
    };
    let mut row_above = Vec::with_capacity(used.above.len() + 1);
    row_above.push(i32::from(used.top_left));
    row_above.extend(used.above.iter().map(|&v| i32::from(v)));
    let mut row_left = Vec::with_capacity(used.left.len() + 1);
    row_left.push(i32::from(used.top_left));
    row_left.extend(used.left.iter().map(|&v| i32::from(v)));

    let is_ver = params.is_mode_ver;
    let angle = params.intra_pred_angle;
    let abs_inv = params.abs_inv_angle;
    let base = height.max(width) + 4;
    let buf_len = base + 2 * width.max(height) + 64;
    let mut ref_above = vec![default; buf_len];
    let mut ref_left = vec![default; buf_len];
    let main_base: usize;
    let side_base: usize;

    if angle < 0 {
        for x in 0..=(width + 1) {
            ref_above[base + x] = row_above[x.min(row_above.len() - 1)];
        }
        for y in 0..=(height + 1) {
            ref_left[base + y] = row_left[y.min(row_left.len() - 1)];
        }
        main_base = base;
        side_base = base;
        let size_side = if is_ver { height } else { width } as i32;
        for k in -size_side..=-1 {
            let proj = ((-k * abs_inv + 256) >> 9).min(size_side) as usize;
            let dst = (base as isize + k as isize) as usize;
            if is_ver {
                ref_above[dst] = ref_left[base + proj];
            } else {
                ref_left[dst] = ref_above[base + proj];
            }
        }
    } else {
        let top_ref_len = 2 * width;
        let left_ref_len = 2 * height;
        for x in 0..=top_ref_len {
            ref_above[base + x] = row_above[x.min(row_above.len() - 1)];
        }
        for y in 0..=left_ref_len {
            ref_left[base + y] = row_left[y.min(row_left.len() - 1)];
        }
        let log2_ratio = width.trailing_zeros() as i32 - height.trailing_zeros() as i32;
        let _s = if is_ver {
            log2_ratio.max(0)
        } else {
            (-log2_ratio).max(0)
        } as usize;
        let max_index = 2usize;
        let ref_length = if is_ver { top_ref_len } else { left_ref_len };
        if is_ver {
            let val = ref_above[base + ref_length];
            for z in 1..=max_index {
                ref_above[base + ref_length + z] = val;
            }
        } else {
            let val = ref_left[base + ref_length];
            for z in 1..=max_index {
                ref_left[base + ref_length + z] = val;
            }
        }
        main_base = base;
        side_base = base;
    }

    let (ref_main, ref_side) = if is_ver {
        (&ref_above, &ref_left)
    } else {
        (&ref_left, &ref_above)
    };
    let (work_w, work_h) = if is_ver {
        (width, height)
    } else {
        (height, width)
    };
    let mut temp = vec![0i32; work_w * work_h];

    if angle == 0 {
        let scale = (work_w.trailing_zeros() + work_h.trailing_zeros() - 2) >> 2;
        let top_left = ref_main[main_base];
        for y in 0..work_h {
            let row = y * work_w;
            for x in 0..work_w {
                temp[row + x] = ref_main[main_base + x + 1];
            }
            if params.apply_pdpc {
                let left = ref_side[side_base + 1 + y];
                let limit = (3usize << scale).min(work_w);
                for x in 0..limit {
                    let wl = 32i32 >> ((2 * x) >> scale);
                    let val = temp[row + x];
                    temp[row + x] = (val + ((wl * (left - top_left) + 32) >> 6)).clamp(0, max_val);
                }
            }
        }
    } else {
        let int_slope = is_integer_slope(angle.abs());
        let mut delta_pos = angle;
        for y in 0..work_h {
            let row = y * work_w;
            let delta_int = delta_pos >> 5;
            let delta_fract = (delta_pos & 31) as usize;
            if !int_slope {
                let gauss = [
                    16 - (delta_fract as i32 >> 1),
                    32 - (delta_fract as i32 >> 1),
                    16 + (delta_fract as i32 >> 1),
                    delta_fract as i32 >> 1,
                ];
                let f = if params.interpolation_flag {
                    &gauss
                } else {
                    &CHROMA_FILTER_4TAP[delta_fract]
                };
                if is_luma {
                    for x in 0..work_w {
                        let i = (main_base as isize + delta_int as isize + x as isize) as usize;
                        let s = f[0] * ref_main[i]
                            + f[1] * ref_main[i + 1]
                            + f[2] * ref_main[i + 2]
                            + f[3] * ref_main[i + 3];
                        temp[row + x] = ((s + 32) >> 6).clamp(0, max_val);
                    }
                } else {
                    for x in 0..work_w {
                        let i = (main_base as isize + delta_int as isize + x as isize + 1) as usize;
                        let p0 = ref_main[i];
                        let p1 = ref_main[i + 1];
                        temp[row + x] =
                            (p0 + (((delta_fract as i32) * (p1 - p0) + 16) >> 5)).clamp(0, max_val);
                    }
                }
            } else {
                for x in 0..work_w {
                    let i = (main_base as isize + delta_int as isize + x as isize + 1) as usize;
                    temp[row + x] = ref_main[i].clamp(0, max_val);
                }
            }
            if params.apply_pdpc {
                let scale = params.angular_scale.max(0) as usize;
                let mut inv_angle_sum = 256i32;
                let limit = (3usize << scale).min(work_w);
                for x in 0..limit {
                    inv_angle_sum += abs_inv;
                    let wl = 32i32 >> ((2 * x) >> scale);
                    let li = side_base + y + ((inv_angle_sum >> 9) as usize) + 1;
                    let left = ref_side[li.min(ref_side.len() - 1)];
                    let val = temp[row + x];
                    temp[row + x] = (val + ((wl * (left - val) + 32) >> 6)).clamp(0, max_val);
                }
            }
            delta_pos += angle;
        }
    }

    let mut out = vec![0u16; width * height];
    if is_ver {
        for (dst, &v) in out.iter_mut().zip(temp.iter()) {
            *dst = v as u16;
        }
    } else {
        for y in 0..work_h {
            for x in 0..work_w {
                out[x * width + y] = temp[y * work_w + x] as u16;
            }
        }
    }
    out
}

/// Downsample luma samples for Cross-Component Linear Model (CCLM) prediction according
/// to `chroma_format` (`4:2:0`, `4:2:2`, or `4:4:4`, ITU-T Rec. H.266 §8.4.5.2.13,
/// VTM `IntraPrediction.cpp:1440-1585`).
///
/// Returns `(ds_block, ds_top, ds_left)` at chroma resolution `(cw, ch)`.
pub fn downsample_luma_for_cclm_format(
    luma_plane: &Plane,
    bx_luma: usize,
    by_luma: usize,
    cw: usize,
    ch: usize,
    chroma_format: ChromaFormatIdc,
    ctu_size_luma: usize,
) -> (Vec<i32>, Vec<i32>, Vec<i32>) {
    match chroma_format {
        ChromaFormatIdc::Chroma420 => {
            let ds_block =
                downsample_luma_for_cclm_420(luma_plane, bx_luma, by_luma, cw, ch, bx_luma > 0);
            let mut ds_top = vec![128i32; cw];
            let first_row_of_ctu = ctu_size_luma > 0 && (by_luma & (ctu_size_luma - 1)) == 0;
            if by_luma > 0 && first_row_of_ctu {
                // At the top CTU boundary the two-row `[1 2 1; 1 2 1] / 8` filter would
                // reach into the previous CTU row, so only the `[1 2 1] / 4` row filter
                // applies (H.266 §8.4.5.2.13, VTM `IntraPrediction.cpp:1447-1452`).
                for x in 0..cw {
                    let lx = bx_luma + 2 * x;
                    let x0 = lx.min(luma_plane.width - 1);
                    let x_r = (lx + 1).min(luma_plane.width - 1);
                    let x_l = if x == 0 && bx_luma == 0 || x0 == 0 {
                        x0
                    } else {
                        x0 - 1
                    };
                    ds_top[x] = (2 * i32::from(luma_plane.get(x0, by_luma - 1))
                        + i32::from(luma_plane.get(x_l, by_luma - 1))
                        + i32::from(luma_plane.get(x_r, by_luma - 1))
                        + 2)
                        >> 2;
                }
            } else if by_luma >= 2 {
                let row = downsample_luma_for_cclm_420(
                    luma_plane,
                    bx_luma,
                    by_luma - 2,
                    cw,
                    1,
                    bx_luma > 0,
                );
                ds_top.copy_from_slice(&row[..cw]);
            }
            let mut ds_left = vec![128i32; ch];
            if bx_luma >= 2 {
                let col =
                    downsample_luma_for_cclm_420(luma_plane, bx_luma - 2, by_luma, 1, ch, true);
                ds_left.copy_from_slice(&col[..ch]);
            }
            (ds_block, ds_top, ds_left)
        }
        ChromaFormatIdc::Chroma422 => {
            let get_y = |x: isize, y: isize| -> i32 {
                let cx = x.clamp(0, luma_plane.width as isize - 1) as usize;
                let cy = y.clamp(0, luma_plane.height as isize - 1) as usize;
                i32::from(luma_plane.get(cx, cy))
            };
            let mut ds_block = vec![0i32; cw * ch];
            for y in 0..ch {
                let ly = (by_luma + y) as isize;
                for x in 0..cw {
                    let lx = (bx_luma + 2 * x) as isize;
                    let left_x = if x == 0 && bx_luma == 0 { lx } else { lx - 1 };
                    ds_block[y * cw + x] =
                        (2 * get_y(lx, ly) + get_y(left_x, ly) + get_y(lx + 1, ly) + 2) >> 2;
                }
            }
            let mut ds_top = vec![128i32; cw];
            if by_luma > 0 {
                let ly = by_luma as isize - 1;
                for x in 0..cw {
                    let lx = (bx_luma + 2 * x) as isize;
                    let left_x = if x == 0 && bx_luma == 0 { lx } else { lx - 1 };
                    ds_top[x] =
                        (2 * get_y(lx, ly) + get_y(left_x, ly) + get_y(lx + 1, ly) + 2) >> 2;
                }
            }
            let mut ds_left = vec![128i32; ch];
            if bx_luma > 0 {
                for y in 0..ch {
                    let ly = (by_luma + y) as isize;
                    let lx = bx_luma as isize - 2;
                    let left_x = if bx_luma >= 2 { lx - 1 } else { lx };
                    ds_left[y] = (2 * get_y(lx.max(0), ly)
                        + get_y(left_x.max(0), ly)
                        + get_y(bx_luma as isize - 1, ly)
                        + 2)
                        >> 2;
                }
            }
            (ds_block, ds_top, ds_left)
        }
        ChromaFormatIdc::Chroma444 | ChromaFormatIdc::Mono400 => {
            let get_y = |x: isize, y: isize| -> i32 {
                let cx = x.clamp(0, luma_plane.width as isize - 1) as usize;
                let cy = y.clamp(0, luma_plane.height as isize - 1) as usize;
                i32::from(luma_plane.get(cx, cy))
            };
            let mut ds_block = vec![0i32; cw * ch];
            for y in 0..ch {
                for x in 0..cw {
                    ds_block[y * cw + x] = get_y((bx_luma + x) as isize, (by_luma + y) as isize);
                }
            }
            let mut ds_top = vec![128i32; cw];
            if by_luma > 0 {
                for x in 0..cw {
                    ds_top[x] = get_y((bx_luma + x) as isize, by_luma as isize - 1);
                }
            }
            let mut ds_left = vec![128i32; ch];
            if bx_luma > 0 {
                for y in 0..ch {
                    ds_left[y] = get_y(bx_luma as isize - 1, (by_luma + y) as isize);
                }
            }
            (ds_block, ds_top, ds_left)
        }
    }
}

/// CCLM mode selector for [`predict_cclm_with_format`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CclmMode {
    /// `LM_CHROMA`.
    Lm,
    /// `MDLM_L`.
    LmL,
    /// `MDLM_T`.
    LmT,
}

/// Predict a chroma block of size `(cw, ch)` using CCLM (`LM_CHROMA`, `MDLM_L`, `MDLM_T`)
/// for any [`ChromaFormatIdc`] (`4:2:0`, `4:2:2`, `4:4:4`, ITU-T Rec. H.266 §8.4.5.2.13).
#[allow(clippy::too_many_arguments)]
pub fn predict_cclm_with_format(
    luma_plane: &Plane,
    chroma_plane: &Plane,
    bx_chroma: usize,
    by_chroma: usize,
    cw: usize,
    ch: usize,
    mode: CclmMode,
    chroma_format: ChromaFormatIdc,
    ctu_size_luma: usize,
) -> Vec<u8> {
    let bx_luma = bx_chroma * chroma_format.sub_width_c();
    let by_luma = by_chroma * chroma_format.sub_height_c();
    let (ds_block, ds_top, ds_left) = downsample_luma_for_cclm_format(
        luma_plane,
        bx_luma,
        by_luma,
        cw,
        ch,
        chroma_format,
        ctu_size_luma,
    );
    let refs_c = gather_references(chroma_plane, bx_chroma, by_chroma, cw, ch);
    let has_top = by_chroma > 0 && mode != CclmMode::LmL;
    let has_left = bx_chroma > 0 && mode != CclmMode::LmT;

    let mut luma_pts = [128i32; 4];
    let mut chroma_pts = [128i32; 4];
    let mut count = 0usize;

    // VTM `xGetLMParameters`: sample the template at `startPos`/`pickStep`
    // positions with the availability-dependent `4` mode. The number of
    // selected samples is at most four per side.
    let above_is_4 = if has_left { 0usize } else { 1usize };
    let left_is_4 = if has_top { 0usize } else { 1usize };
    if has_top {
        let start = cw >> (2 + above_is_4);
        let step = 1.max(cw >> (1 + above_is_4));
        let cnt = cw.min((1 + above_is_4) << 1);
        let mut pos = start;
        for i in 0..cnt {
            let idx = pos.min(cw - 1);
            luma_pts[i] = ds_top[idx];
            chroma_pts[i] = i32::from(refs_c.above[idx]);
            count += 1;
            pos += step;
        }
    }
    if has_left {
        let start = ch >> (2 + left_is_4);
        let step = 1.max(ch >> (1 + left_is_4));
        let cnt = ch.min((1 + left_is_4) << 1);
        let mut pos = start;
        for _ in 0..cnt {
            let idx = pos.min(ch - 1);
            luma_pts[count] = ds_left[idx];
            chroma_pts[count] = i32::from(refs_c.left[idx]);
            count += 1;
            pos += step;
        }
    }

    let params = derive_cclm_params_from_4_samples(luma_pts, chroma_pts, count, 8);

    ds_block
        .into_iter()
        .map(|y_val| {
            let pred = ((y_val * params.a) >> params.shift) + params.b;
            pred.clamp(0, 255) as u8
        })
        .collect()
}

/// Normative Palette run context look-up table for `copy_above_palette_indices_flag == 1`
/// (`g_paletteRunTopLut`, VTM `Rom.cpp:617`).
pub const PALETTE_RUN_TOP_LUT: [usize; 5] = [0, 1, 1, 2, 2];

/// Normative Palette run context look-up table for `copy_above_palette_indices_flag == 0`
/// (`g_paletteRunLeftLut`, VTM `Rom.cpp:618`).
pub const PALETTE_RUN_LEFT_LUT: [usize; 5] = [0, 1, 2, 3, 4];

/// Normative Palette index threshold (`RUN_IDX_THRE = 4`, VTM `CommonDef.h`).
pub const PALETTE_RUN_IDX_THRE: usize = 4;

/// Base-2 logarithm of the Palette coding group size (`LOG2_PALETTE_CG_SIZE = 4`, 16 samples).
pub const LOG2_PALETTE_CG_SIZE: usize = 4;

/// Derive the CABAC context offset (`0..=7`) for `palette_run_prefix` bin 0
/// (ITU-T Rec. H.266 §9.3.4.2.10, VTM `ContextModelling.cpp:365-375`).
#[inline]
pub fn derive_palette_run_ctx(prev_index: u8, copy_above: bool) -> usize {
    if copy_above {
        5 + PALETTE_RUN_TOP_LUT[(prev_index as usize).min(4)]
    } else {
        PALETTE_RUN_LEFT_LUT[(prev_index as usize).min(4)]
    }
}

/// Normative Palette coding unit description for H.266 screen content coding
/// (ITU-T Rec. H.266 §7.3.11.6, §8.4.5.3; VTM `CABACWriter.cpp:1440-1695`).
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct PaletteBlock {
    /// Explicit palette table entries `[Y, Cb, Cr]` (up to `max_palette_size = 31`).
    pub entries: Vec<[u16; 3]>,
    /// Whether `palette_transpose_flag` is set (vertical traverse scan instead of horizontal).
    pub transpose: bool,
    /// Whether any sample in the block uses the escape index (`index == entries.len()`).
    pub escape_present: bool,
    /// Per-position `copy_above_palette_indices_flag` in traverse scan order.
    pub copy_above_flags: Vec<bool>,
    /// Per-position palette index in traverse scan order (`0..=entries.len()`).
    pub index_map: Vec<u8>,
    /// Quantised escape sample values `[Y, Cb, Cr]` for positions with `index == entries.len()`.
    pub escape_samples: Vec<[u16; 3]>,
}

/// Normative H.266 §6.5.3 horizontal/vertical traverse scan coordinate `(x, y)` for a
/// `width x height` Palette block at scan position `scan_pos`.
#[inline]
pub fn palette_traverse_coord(
    scan_pos: usize,
    width: usize,
    height: usize,
    transpose: bool,
) -> (usize, usize) {
    if !transpose {
        let y = scan_pos / width;
        let rem = scan_pos % width;
        let x = if (y & 1) == 1 { width - 1 - rem } else { rem };
        (x, y)
    } else {
        let x = scan_pos / height;
        let rem = scan_pos % height;
        let y = if (x & 1) == 1 { height - 1 - rem } else { rem };
        (x, y)
    }
}

/// Build a [`PaletteBlock`] from a luma/chroma block by clustering distinct sample values
/// up to `max_entries` (default `15`) and assigning remaining samples to nearest entry or escape.
pub fn build_palette_from_block(
    y_samples: &[u16],
    u_samples: &[u16],
    v_samples: &[u16],
    width: usize,
    height: usize,
    max_entries: usize,
) -> PaletteBlock {
    let n = width * height;
    let cap = max_entries.clamp(1, 31);
    let mut entries: Vec<[u16; 3]> = Vec::new();
    for pos in 0..n {
        let y = y_samples.get(pos).copied().unwrap_or(128);
        let u = u_samples.get(pos).copied().unwrap_or(128);
        let v = v_samples.get(pos).copied().unwrap_or(128);
        let trip = [y, u, v];
        if !entries.contains(&trip) && entries.len() < cap {
            entries.push(trip);
        }
    }
    if entries.is_empty() {
        entries.push([128, 128, 128]);
    }
    let esc_idx = entries.len() as u8;
    let mut index_map = vec![0u8; n];
    let mut copy_above_flags = vec![false; n];
    let mut escape_samples = Vec::new();
    let mut escape_present = false;

    for scan_pos in 0..n {
        let (x, y) = palette_traverse_coord(scan_pos, width, height, false);
        let raster = y * width + x;
        let trip = [
            y_samples.get(raster).copied().unwrap_or(128),
            u_samples.get(raster).copied().unwrap_or(128),
            v_samples.get(raster).copied().unwrap_or(128),
        ];
        if let Some(idx) = entries.iter().position(|&e| e == trip) {
            index_map[scan_pos] = idx as u8;
        } else {
            index_map[scan_pos] = esc_idx;
            escape_present = true;
            escape_samples.push(trip);
        }
        let _ = &mut copy_above_flags;
    }

    PaletteBlock {
        entries,
        transpose: false,
        escape_present,
        copy_above_flags,
        index_map,
        escape_samples,
    }
}

/// Normatively reconstruct the `(y_out, u_out, v_out)` sample arrays of size `width * height`
/// from a decoded [`PaletteBlock`] (ITU-T Rec. H.266 §8.4.5.3).
pub fn reconstruct_palette_block(
    palette: &PaletteBlock,
    width: usize,
    height: usize,
    bit_depth: u8,
) -> (Vec<u16>, Vec<u16>, Vec<u16>) {
    let n = width * height;
    let mid = 1u16 << (bit_depth.clamp(8, 12) - 1);
    let max_v = (1u16 << bit_depth.clamp(8, 12)) - 1;
    let mut y_out = vec![mid; n];
    let mut u_out = vec![mid; n];
    let mut v_out = vec![mid; n];
    let esc_idx = palette.entries.len() as u8;
    let mut esc_cursor = 0usize;

    for scan_pos in 0..n {
        let (x, y) = palette_traverse_coord(scan_pos, width, height, palette.transpose);
        let raster = y * width + x;
        let idx = palette.index_map.get(scan_pos).copied().unwrap_or(0);
        let trip = if palette.escape_present && idx >= esc_idx {
            let s = palette
                .escape_samples
                .get(esc_cursor)
                .copied()
                .unwrap_or([mid, mid, mid]);
            esc_cursor += 1;
            s
        } else {
            palette
                .entries
                .get(idx as usize)
                .copied()
                .unwrap_or([mid, mid, mid])
        };
        y_out[raster] = trip[0].min(max_v);
        u_out[raster] = trip[1].min(max_v);
        v_out[raster] = trip[2].min(max_v);
    }

    (y_out, u_out, v_out)
}

/// Gather and pad reference samples from a 16-bit [`Plane16`] at Multiple Reference Line
/// index `mrl_idx` (`0`, `1`, or `2`, corresponding to line offset `1`, `2`, or `3` above/left,
/// ITU-T Rec. H.266 §8.4.5.2.2, VTM `IntraPrediction.cpp`).
pub fn gather_references_mrl_16(
    plane: &Plane16,
    x: usize,
    y: usize,
    width: usize,
    height: usize,
    mrl_idx: u8,
) -> ReferenceSamples16 {
    let line_off = match mrl_idx {
        1 => 2usize,
        2 => 3usize,
        _ => 1usize,
    };
    let default_val = 1u16 << (plane.bit_depth.clamp(8, 12) - 1);
    let above_len = 2 * width;
    let left_len = 2 * height;
    let has_above = y >= line_off;
    let has_left = x >= line_off;

    let mut above = vec![default_val; above_len];
    let mut left = vec![default_val; left_len];

    if has_above {
        let avail_w = (plane.width.saturating_sub(x)).min(above_len);
        for i in 0..avail_w {
            above[i] = plane.get(x + i, y - line_off);
        }
        let pad = above[avail_w.saturating_sub(1)];
        for item in above.iter_mut().skip(avail_w) {
            *item = pad;
        }
    }

    if has_left {
        let avail_h = (plane.height.saturating_sub(y)).min(height);
        for j in 0..avail_h {
            left[j] = plane.get(x - line_off, y + j);
        }
        let pad = left[avail_h.saturating_sub(1)];
        for item in left.iter_mut().skip(avail_h) {
            *item = pad;
        }
    }

    if has_above && !has_left {
        left.fill(above[0]);
    } else if !has_above && has_left {
        above.fill(left[0]);
    }

    let top_left = if has_above && has_left {
        plane.get(x - line_off, y - line_off)
    } else if has_above {
        above[0]
    } else if has_left {
        left[0]
    } else {
        default_val
    };

    ReferenceSamples16 {
        top_left,
        above,
        left,
        bit_depth: plane.bit_depth,
    }
}

/// Downsample luma samples from a 16-bit [`Plane16`] for CCLM prediction according to
/// `chroma_format` (`4:2:0`, `4:2:2`, `4:4:4`, ITU-T Rec. H.266 §8.4.5.2.13,
/// VTM `IntraPrediction.cpp:1440-1585`).
pub fn downsample_luma_for_cclm_format_16(
    luma_plane: &Plane16,
    bx_luma: usize,
    by_luma: usize,
    cw: usize,
    ch: usize,
    chroma_format: ChromaFormatIdc,
    ctu_size_luma: usize,
) -> (Vec<i32>, Vec<i32>, Vec<i32>) {
    let bd = luma_plane.bit_depth.clamp(8, 12);
    let mid = 1i32 << (bd - 1);
    let get_y = |x: isize, y: isize| -> i32 {
        let cx = x.clamp(0, luma_plane.width as isize - 1) as usize;
        let cy = y.clamp(0, luma_plane.height as isize - 1) as usize;
        i32::from(luma_plane.get(cx, cy))
    };
    match chroma_format {
        ChromaFormatIdc::Chroma420 => {
            let ds_region = |rx: usize, ry: usize, rw: usize, rh: usize, has_l: bool| -> Vec<i32> {
                let mut out = vec![0i32; rw * rh];
                for y in 0..rh {
                    let ly = (ry + 2 * y) as isize;
                    for x in 0..rw {
                        let lx = (rx + 2 * x) as isize;
                        let left_x = if x == 0 && !has_l { lx } else { lx - 1 };
                        let r0 = 2 * get_y(lx, ly) + get_y(left_x, ly) + get_y(lx + 1, ly);
                        let r1 =
                            2 * get_y(lx, ly + 1) + get_y(left_x, ly + 1) + get_y(lx + 1, ly + 1);
                        out[y * rw + x] = (r0 + r1 + 4) >> 3;
                    }
                }
                out
            };
            let ds_block = ds_region(bx_luma, by_luma, cw, ch, bx_luma > 0);
            let mut ds_top = vec![mid; cw];
            let first_row_of_ctu = ctu_size_luma > 0 && (by_luma & (ctu_size_luma - 1)) == 0;
            if by_luma > 0 && first_row_of_ctu {
                // At the top CTU boundary the two-row `[1 2 1; 1 2 1] / 8` filter would
                // reach into the previous CTU row, so only the `[1 2 1] / 4` row filter
                // applies (H.266 §8.4.5.2.13, VTM `IntraPrediction.cpp:1447-1452`).
                for x in 0..cw {
                    let lx = (bx_luma + 2 * x) as isize;
                    let y = by_luma as isize - 1;
                    let x0 = lx.clamp(0, luma_plane.width as isize - 1);
                    let x_r = (lx + 1).clamp(0, luma_plane.width as isize - 1);
                    let x_l = if x == 0 && bx_luma == 0 || x0 == 0 {
                        x0
                    } else {
                        x0 - 1
                    };
                    ds_top[x] = (2 * get_y(x0, y) + get_y(x_l, y) + get_y(x_r, y) + 2) >> 2;
                }
            } else if by_luma >= 2 {
                let row = ds_region(bx_luma, by_luma - 2, cw, 1, bx_luma > 0);
                ds_top.copy_from_slice(&row[..cw]);
            }
            let mut ds_left = vec![mid; ch];
            if bx_luma >= 2 {
                let col = ds_region(bx_luma - 2, by_luma, 1, ch, true);
                ds_left.copy_from_slice(&col[..ch]);
            }
            (ds_block, ds_top, ds_left)
        }
        ChromaFormatIdc::Chroma422 => {
            let mut ds_block = vec![0i32; cw * ch];
            for y in 0..ch {
                let ly = (by_luma + y) as isize;
                for x in 0..cw {
                    let lx = (bx_luma + 2 * x) as isize;
                    let left_x = if x == 0 && bx_luma == 0 { lx } else { lx - 1 };
                    ds_block[y * cw + x] =
                        (2 * get_y(lx, ly) + get_y(left_x, ly) + get_y(lx + 1, ly) + 2) >> 2;
                }
            }
            let mut ds_top = vec![mid; cw];
            if by_luma > 0 {
                let ly = by_luma as isize - 1;
                for x in 0..cw {
                    let lx = (bx_luma + 2 * x) as isize;
                    let left_x = if x == 0 && bx_luma == 0 { lx } else { lx - 1 };
                    ds_top[x] =
                        (2 * get_y(lx, ly) + get_y(left_x, ly) + get_y(lx + 1, ly) + 2) >> 2;
                }
            }
            let mut ds_left = vec![mid; ch];
            if bx_luma > 0 {
                for y in 0..ch {
                    let ly = (by_luma + y) as isize;
                    let lx = bx_luma as isize - 2;
                    let left_x = if bx_luma >= 2 { lx - 1 } else { lx };
                    ds_left[y] = (2 * get_y(lx.max(0), ly)
                        + get_y(left_x.max(0), ly)
                        + get_y(bx_luma as isize - 1, ly)
                        + 2)
                        >> 2;
                }
            }
            (ds_block, ds_top, ds_left)
        }
        ChromaFormatIdc::Chroma444 | ChromaFormatIdc::Mono400 => {
            let mut ds_block = vec![0i32; cw * ch];
            for y in 0..ch {
                for x in 0..cw {
                    ds_block[y * cw + x] = get_y((bx_luma + x) as isize, (by_luma + y) as isize);
                }
            }
            let mut ds_top = vec![mid; cw];
            if by_luma > 0 {
                for x in 0..cw {
                    ds_top[x] = get_y((bx_luma + x) as isize, by_luma as isize - 1);
                }
            }
            let mut ds_left = vec![mid; ch];
            if bx_luma > 0 {
                for y in 0..ch {
                    ds_left[y] = get_y(bx_luma as isize - 1, (by_luma + y) as isize);
                }
            }
            (ds_block, ds_top, ds_left)
        }
    }
}

/// Predict a 16-bit chroma block of size `(cw, ch)` using CCLM (`LM_CHROMA`, `MDLM_L`, `MDLM_T`)
/// for any [`ChromaFormatIdc`] and `bit_depth` in `8..=12` (ITU-T Rec. H.266 §8.4.5.2.13,
/// VTM `IntraPrediction.cpp:266-360`).
#[allow(clippy::too_many_arguments)]
pub fn predict_cclm_with_format_16(
    luma_plane: &Plane16,
    chroma_plane: &Plane16,
    bx_chroma: usize,
    by_chroma: usize,
    cw: usize,
    ch: usize,
    mode: CclmMode,
    chroma_format: ChromaFormatIdc,
    ctu_size_luma: usize,
) -> Vec<u16> {
    let bd = chroma_plane.bit_depth.clamp(8, 12);
    let max_val = chroma_plane.max_sample();
    let mid = 1i32 << (bd - 1);
    let bx_luma = bx_chroma * chroma_format.sub_width_c();
    let by_luma = by_chroma * chroma_format.sub_height_c();
    let (ds_block, ds_top, ds_left) = downsample_luma_for_cclm_format_16(
        luma_plane,
        bx_luma,
        by_luma,
        cw,
        ch,
        chroma_format,
        ctu_size_luma,
    );
    let refs_c = gather_references_16(chroma_plane, bx_chroma, by_chroma, cw, ch);
    let has_top = by_chroma > 0 && mode != CclmMode::LmL;
    let has_left = bx_chroma > 0 && mode != CclmMode::LmT;

    let mut luma_pts = [mid; 4];
    let mut chroma_pts = [mid; 4];
    let mut count = 0usize;

    if has_top && has_left {
        let x0 = cw / 4;
        let x1 = (3 * cw) / 4;
        let y0 = ch / 4;
        let y1 = (3 * ch) / 4;
        luma_pts = [ds_top[x0], ds_top[x1], ds_left[y0], ds_left[y1]];
        chroma_pts = [
            i32::from(refs_c.above[x0]),
            i32::from(refs_c.above[x1]),
            i32::from(refs_c.left[y0]),
            i32::from(refs_c.left[y1]),
        ];
        count = 4;
    } else if has_top {
        for i in 0..4.min(cw) {
            let idx = ((2 * i + 1) * cw) / 8;
            luma_pts[i] = ds_top[idx.min(cw - 1)];
            chroma_pts[i] = i32::from(refs_c.above[idx.min(cw - 1)]);
            count += 1;
        }
    } else if has_left {
        for i in 0..4.min(ch) {
            let idx = ((2 * i + 1) * ch) / 8;
            luma_pts[i] = ds_left[idx.min(ch - 1)];
            chroma_pts[i] = i32::from(refs_c.left[idx.min(ch - 1)]);
            count += 1;
        }
    }

    let params = derive_cclm_params_from_4_samples(luma_pts, chroma_pts, count, bd);
    ds_block
        .into_iter()
        .map(|y_val| {
            let pred = ((y_val * params.a) >> params.shift) + params.b;
            pred.clamp(0, max_val) as u16
        })
        .collect()
}

/// Choose the lowest-SAD intra mode (`Planar`, `Dc`, or `Angular(2..=66)`) on a 16-bit [`Plane16`].
pub fn choose_intra_mode_16(
    recon: &Plane16,
    src: &Plane16,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
    is_luma: bool,
) -> IntraPredMode {
    let mut best_mode = IntraPredMode::Planar;
    let mut best_sad = u64::MAX;
    let candidates = [
        IntraPredMode::Planar,
        IntraPredMode::Dc,
        IntraPredMode::Angular(18),
        IntraPredMode::Angular(50),
        IntraPredMode::Angular(2),
        IntraPredMode::Angular(34),
        IntraPredMode::Angular(66),
    ];
    for mode in candidates {
        let pred = predict_block_16(recon, bx, by, w, h, is_luma, mode);
        let mut sad = 0u64;
        for y in 0..h {
            let sy = (by + y).min(src.height.saturating_sub(1));
            for x in 0..w {
                let sx = (bx + x).min(src.width.saturating_sub(1));
                sad += u64::from(src.get(sx, sy).abs_diff(pred[y * w + x]));
            }
        }
        if sad < best_sad {
            best_sad = sad;
            best_mode = mode;
        }
    }
    best_mode
}

/// Normative 16-bit Matrix-based Intra Prediction (`MIP`, `bit_depth` in `8..=12`,
/// ITU-T Rec. H.266 §8.4.5.2.11, VTM `IntraPrediction.cpp:1839-1950`).
pub fn predict_mip_16(
    refs: &ReferenceSamples16,
    width: usize,
    height: usize,
    mode_idx: u8,
    transposed: bool,
) -> Vec<u16> {
    let bd = refs.bit_depth.clamp(8, 12);
    let widened = RefSamples {
        top_left: i32::from(refs.top_left),
        above: refs.above.iter().map(|&v| i32::from(v)).collect(),
        left: refs.left.iter().map(|&v| i32::from(v)).collect(),
    };
    predict_mip_bd(&widened, width, height, mode_idx, transposed, bd)
        .into_iter()
        .map(|v| v.clamp(0, i32::from(u16::MAX)) as u16)
        .collect()
}

/// Evaluate all `(transposed, mode_idx)` MIP candidates for an 8-bit luma block `(bx, by, w, h)`
/// and return `(best_transposed, best_mode_idx, best_pred, best_sad)`.
pub fn choose_best_mip_mode(
    refs: &RefSamples,
    src: &Plane,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
) -> (bool, u8, Vec<i32>, u64) {
    let num_modes = get_num_modes_mip(w, h) as u8;
    let mut best_tr = false;
    let mut best_idx = 0u8;
    let mut best_pred = vec![128i32; w * h];
    let mut best_sad = u64::MAX;
    for tr in [false, true] {
        for idx in 0..num_modes {
            let pred = predict_mip(refs, w, h, idx, tr);
            let mut sad = 0u64;
            for y in 0..h {
                for x in 0..w {
                    let s = i32::from(src.get(bx + x, by + y));
                    sad += (s - pred[y * w + x]).unsigned_abs() as u64;
                }
            }
            if sad < best_sad {
                best_sad = sad;
                best_tr = tr;
                best_idx = idx;
                best_pred = pred;
            }
        }
    }
    (best_tr, best_idx, best_pred, best_sad)
}

/// Evaluate all `(transposed, mode_idx)` MIP candidates for a 16-bit luma block `(bx, by, w, h)`
/// and return `(best_transposed, best_mode_idx, best_pred, best_sad)`.
pub fn choose_best_mip_mode_16(
    refs: &ReferenceSamples16,
    src: &Plane16,
    bx: usize,
    by: usize,
    w: usize,
    h: usize,
) -> (bool, u8, Vec<u16>, u64) {
    let num_modes = get_num_modes_mip(w, h) as u8;
    let mut best_tr = false;
    let mut best_idx = 0u8;
    let mut best_pred = vec![1u16 << (src.bit_depth.clamp(8, 12) - 1); w * h];
    let mut best_sad = u64::MAX;
    for tr in [false, true] {
        for idx in 0..num_modes {
            let pred = predict_mip_16(refs, w, h, idx, tr);
            let mut sad = 0u64;
            for y in 0..h {
                for x in 0..w {
                    let s = src.get(bx + x, by + y);
                    sad += u64::from(s.abs_diff(pred[y * w + x]));
                }
            }
            if sad < best_sad {
                best_sad = sad;
                best_tr = tr;
                best_idx = idx;
                best_pred = pred;
            }
        }
    }
    (best_tr, best_idx, best_pred, best_sad)
}

/// Apply forward Block DPCM (BDPCM) differencing to quantised transform-skip levels
/// along rows (`vertical == false`) or columns (`vertical == true`)
/// (ITU-T Rec. H.266 §8.4.5.2.6 / §8.7.4.2, VTM `Quant.cpp:142-180`).
pub fn apply_bdpcm_forward(levels: &[i32], w: usize, h: usize, vertical: bool) -> Vec<i32> {
    let mut out = levels.to_vec();
    if !vertical {
        for y in 0..h {
            for x in (1..w).rev() {
                out[y * w + x] -= out[y * w + (x - 1)];
            }
        }
    } else {
        for y in (1..h).rev() {
            for x in 0..w {
                out[y * w + x] -= out[(y - 1) * w + x];
            }
        }
    }
    out
}

/// Apply normative inverse Block DPCM (`invResDPCM`) accumulation to decoded transform-skip
/// levels along rows (`vertical == false`) or columns (`vertical == true`)
/// (ITU-T Rec. H.266 §8.7.4.2 Eq. 1177–1178, VTM `Quant.cpp:142-180`).
pub fn apply_bdpcm_inverse(levels: &[i32], w: usize, h: usize, vertical: bool) -> Vec<i32> {
    let mut out = levels.to_vec();
    if !vertical {
        for y in 0..h {
            for x in 1..w {
                out[y * w + x] = (out[y * w + x] + out[y * w + (x - 1)]).clamp(-32768, 32767);
            }
        }
    } else {
        for y in 1..h {
            for x in 0..w {
                out[y * w + x] = (out[y * w + x] + out[(y - 1) * w + x]).clamp(-32768, 32767);
            }
        }
    }
    out
}

