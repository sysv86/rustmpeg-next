    let tr_shift =
        transform_shift_rect_bd(width, height, bit_depth) + if needs_sqrt2 { -1 } else { 0 };
    let shift = 7 - qp_per - tr_shift;
    let mut inv_q_scale = i64::from(if needs_sqrt2 {
        INV_QUANT_SCALES_SQRT2[qp_rem]
    } else {
        INV_QUANT_SCALES[qp_rem]
    });
    if shift < 0 {
        inv_q_scale <<= -shift;
    }
    let add = if shift > 0 { 1i64 << (shift - 1) } else { 0 };
    let rshift = shift.max(0);

    let mut state = 0i32;
