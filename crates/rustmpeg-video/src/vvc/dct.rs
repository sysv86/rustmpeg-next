/// Return the flattened, row-major DCT-2 matrix for a transform dimension (`2..=64`).
pub fn dct2_matrix_any(size: usize) -> Option<&'static [i32]> {
    match size {
        2 => Some(&DCT2_2),
        4 => Some(&DCT2_4),
        8 => Some(&DCT2_8),
        16 => Some(&DCT2_16),
        32 => Some(&DCT2_32),
        64 => Some(&DCT2_64),
        _ => None,
    }
}

/// Return the flattened, row-major DCT-2 matrix for a square block size (`4..=32`).
fn dct2_matrix(size: usize) -> Option<&'static [i32]> {
    match size {
        4 => Some(&DCT2_4),
        8 => Some(&DCT2_8),
        16 => Some(&DCT2_16),
        32 => Some(&DCT2_32),
        _ => None,
    }
}

/// Return the flattened, row-major matrix for a transform type and size (`4..=32`).
fn matrix_for(tr_type: TrType, size: usize) -> Option<&'static [i32]> {
    match (tr_type, size) {
        (TrType::Dct2, _) => dct2_matrix(size),
        (TrType::Dst7, 4) => Some(&DST7_4),
        (TrType::Dst7, 8) => Some(&DST7_8),
        (TrType::Dst7, 16) => Some(&DST7_16),
        (TrType::Dst7, 32) => Some(&DST7_32),
        (TrType::Dct8, 4) => Some(&DCT8_4),
        (TrType::Dct8, 8) => Some(&DCT8_8),
        (TrType::Dct8, 16) => Some(&DCT8_16),
        (TrType::Dct8, 32) => Some(&DCT8_32),
        _ => None,
    }
}

/// Return the flattened, row-major matrix for any 1-D transform dimension (`2..=64`).
pub fn matrix_for_any(tr_type: TrType, size: usize) -> Option<&'static [i32]> {
    match tr_type {
        TrType::Dct2 => dct2_matrix_any(size),
        TrType::Dst7 | TrType::Dct8 => matrix_for(tr_type, size),
    }
}

/// `true` when `size` is a supported square transform dimension (`4..=32`) for the baseline API.
pub fn is_supported(size: usize) -> bool {
    (MIN_SIZE..=MAX_SIZE).contains(&size) && size.is_power_of_two()
}

/// `true` when `(width, height)` is a valid H.266 transform block size (`1..=64` power of two,
/// including `1xN` / `Nx1` ISP 1-D subpartitions with `width * height >= 2`).
pub fn is_supported_rect(width: usize, height: usize) -> bool {
    (1..=64).contains(&width)
        && (1..=64).contains(&height)
        && width.saturating_mul(height) >= 2
        && width.is_power_of_two()
        && height.is_power_of_two()
}

#[inline]
fn log2(size: usize) -> i32 {
    size.trailing_zeros() as i32
}

/// VTM `getTransformShift(8, size, 15)` for a square block.
#[inline]
fn transform_shift(size: usize) -> i32 {
    MAX_LOG2_TR_DYNAMIC_RANGE - 8 - log2(size)
}

/// VTM `getTransformShift(8, Size(w, h), 15)` for a rectangular `(w, h)` block.
#[inline]
pub fn transform_shift_rect(width: usize, height: usize) -> i32 {
    MAX_LOG2_TR_DYNAMIC_RANGE - 8 - ((log2(width) + log2(height)) >> 1)
}

#[inline]
fn clip_transform(value: i64) -> i32 {
    value.clamp(-32768, 32767) as i32
}

/// Forward transform of one square block (VTM `TrQuant::xT`).
pub fn forward_transform(
    size: usize,
    residual: &[i32],
    tr_hor: TrType,
    tr_ver: TrType,
    skip_width: usize,
    skip_height: usize,
) -> Result<Vec<i32>, &'static str> {
    let mh = matrix_for(tr_hor, size).ok_or("unsupported horizontal transform")?;
    let mv = matrix_for(tr_ver, size).ok_or("unsupported vertical transform")?;
    if residual.len() != size * size {
        return Err("residual length does not match the transform size");
    }
    if skip_width >= size || skip_height >= size {
        return Err("transform zero-out leaves no coefficients");
    }
    let lg = log2(size);
    let shift_1st = (lg + 8 + TRANSFORM_MATRIX_SHIFT) - MAX_LOG2_TR_DYNAMIC_RANGE;
    let shift_2nd = lg + TRANSFORM_MATRIX_SHIFT;
    let add_1st = 1i64 << (shift_1st - 1);
    let add_2nd = 1i64 << (shift_2nd - 1);
    let cutoff_w = size - skip_width;
    let cutoff_h = size - skip_height;

    let mut tmp = vec![0i32; size * size];
    for y in 0..size {
        for k in 0..cutoff_w {
            let mut sum = 0i64;
            for n in 0..size {
                sum += i64::from(mh[k * size + n]) * i64::from(residual[y * size + n]);
            }
            tmp[k * size + y] = ((sum + add_1st) >> shift_1st) as i32;
        }
    }

    let mut out = vec![0i32; size * size];
    for v in 0..cutoff_h {
        for k in 0..cutoff_w {
            let mut sum = 0i64;
            for y in 0..size {
                sum += i64::from(mv[v * size + y]) * i64::from(tmp[k * size + y]);
            }
            out[v * size + k] = ((sum + add_2nd) >> shift_2nd) as i32;
        }
    }
    Ok(out)
}

/// Forward 2-D transform of a rectangular `(width, height)` block (`2..=64` on each axis,
/// including automatic high-frequency zero-out beyond `32` for `64`-point DCT-2 and beyond
/// `16` for `32`-point MTS, VTM `TrQuant::xT`, `TrQuant.cpp:755-828`).
pub fn forward_transform_rect(
    width: usize,
    height: usize,
    residual: &[i32],
    tr_hor: TrType,
    tr_ver: TrType,
    extra_skip_width: usize,
    extra_skip_height: usize,
) -> Result<Vec<i32>, &'static str> {
    let mh = matrix_for_any(tr_hor, width).ok_or("unsupported horizontal transform")?;
    let mv = matrix_for_any(tr_ver, height).ok_or("unsupported vertical transform")?;
    if residual.len() != width * height {
        return Err("residual length does not match the transform dimensions");
    }
    let default_skip_w = if tr_hor != TrType::Dct2 && width == 32 {
        16
    } else {
        width.saturating_sub(32)
    };
    let default_skip_h = if tr_ver != TrType::Dct2 && height == 32 {
        16
    } else {
        height.saturating_sub(32)
    };
    let skip_w = default_skip_w.max(extra_skip_width);
    let skip_h = default_skip_h.max(extra_skip_height);
    if skip_w >= width || skip_h >= height {
        return Err("transform zero-out leaves no coefficients");
    }

    if width == 1 || height == 1 {
        return forward_transform_rect_bd(
            width,
            height,
            residual,
            tr_hor,
            tr_ver,
            extra_skip_width,
            extra_skip_height,
            8,
        );
    }
    let lg_w = log2(width);
    let lg_h = log2(height);
    let shift_1st = (lg_w + 8 + TRANSFORM_MATRIX_SHIFT) - MAX_LOG2_TR_DYNAMIC_RANGE;
    let shift_2nd = lg_h + TRANSFORM_MATRIX_SHIFT;
    let add_1st = if shift_1st > 0 {
        1i64 << (shift_1st - 1)
    } else {
        0
    };
    let add_2nd = 1i64 << (shift_2nd - 1);
    let cutoff_w = width - skip_w;
    let cutoff_h = height - skip_h;

    let mut tmp = vec![0i32; width * height];
    for y in 0..height {
        for k in 0..cutoff_w {
            let mut sum = 0i64;
            for n in 0..width {
                sum += i64::from(mh[k * width + n]) * i64::from(residual[y * width + n]);
            }
            tmp[k * height + y] = ((sum + add_1st) >> shift_1st) as i32;
        }
    }

    let mut out = vec![0i32; width * height];
    for v in 0..cutoff_h {
        for k in 0..cutoff_w {
            let mut sum = 0i64;
            for y in 0..height {
                sum += i64::from(mv[v * height + y]) * i64::from(tmp[k * height + y]);
            }
            out[v * width + k] = clip_transform((sum + add_2nd) >> shift_2nd);
        }
    }
    Ok(out)
}

