//! DCT-2, DST-7 and DCT-8 primary transforms and regular / dependent
//! quantisation for H.266/VVC (ITU-T Rec. H.266 §8.7.3, §8.7.4).
//!
//! Algorithms and integer matrices derived from VTM 24.0 (`RomTr.cpp`,
//! `Rom.cpp`, `TrQuant.cpp`, `DepQuant.cpp`, BSD-3-Clause, Copyright (c)
//! 2010-2026 ITU/ISO/IEC). See `THIRD_PARTY.md`.
//!
//! Supported features:
//! - 1-D and 2-D DCT-2 for lengths `2, 4, 8, 16, 32, 64` (with high-frequency
//!   zero-out beyond 32 coefficients for 64-point transforms).
//! - 1-D and 2-D DST-7 and DCT-8 for lengths `4, 8, 16, 32` (with high-frequency
//!   zero-out beyond 16 coefficients for 32-point MTS transforms).
//! - Square (`forward_transform`, `inverse_transform`) and rectangular
//!   (`forward_transform_rect`, `inverse_transform_rect`) 2-D transforms.
//! - Regular scalar quantisation and inverse quantisation (`quantize_dct`,
//!   `dequantize_dct`, `quantize_rect`, `dequantize_rect`) including the
//!   `(log2(w) + log2(h)) & 1 == 1` `sqrt(2)` scale adjustment (`Rom.cpp:468-478`).
//! - Dependent Quantisation (`dequantize_dep_quant`, `quantize_dep_quant`,
//!   `DepQuant.cpp:688-801`) with the 4-state transition table `32040`.
//! - Explicit scaling list dequantisation (`dequantize_with_scaling_list`).

