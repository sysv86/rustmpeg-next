//! AV2 coefficient CDF tables (base-token coefficient coding).
//!
//! The coefficient coding syntax used by the current AV2 bitstream (dav2d
//! bff8e5c) codes transform coefficients with base tokens (`coeff_base_bob`,
//! `coeff_base_idtx`, `eob_base_y_tok_hf`, ...) rather than the older
//! `coeff_base_eob` layout.
//!
//! The default values below originate from the reference decoder's coefficient
//! CDF tables: Copyright (c) 2018-2026, VideoLAN and dav2d authors and
//! Copyright (c) 2018-2026, Two Orioles, LLC; BSD-2-Clause. They are stored
//! here in the encoder's forward-CDF representation (the probability value `p`
//! is `32768 - p_dav2d`), with the one-word adaptation meta
//! `pc = (adaptation_rate << 8) | count` retained at index `n_symbols`
//! (`[probs.., pc]`, padded for the vectorised decoder).

#[derive(Clone, Copy)]
#[repr(C)]
pub struct CdfCoefContext {
    pub data: [u16; 4676],
}

impl Default for CdfCoefContext {
    fn default() -> Self {
        Self { data: [0; 4676] }
    }
}

impl CdfCoefContext {
    pub fn skip(&mut self, i: usize, j: usize, k: usize) -> &mut [u16] {
        let o = i * 100 + j * 20 + k * 2;
        &mut self.data[o..o + 2]
    }
    pub fn skip_v(&mut self, k: usize) -> &mut [u16] {
        let o = 4418 + k * 2;
        &mut self.data[o..o + 2]
    }
    pub fn eob_bin_16(&mut self, i: usize) -> &mut [u16] {
        let o = 200 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_32(&mut self, i: usize) -> &mut [u16] {
        let o = 224 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_64(&mut self, i: usize) -> &mut [u16] {
        let o = 248 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_128(&mut self, i: usize) -> &mut [u16] {
        let o = 272 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_256(&mut self, i: usize) -> &mut [u16] {
        let o = 296 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_512(&mut self, i: usize) -> &mut [u16] {
        let o = 320 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_bin_1024(&mut self, i: usize) -> &mut [u16] {
        let o = 344 + i * 8;
        &mut self.data[o..o + 8]
    }
    pub fn eob_hi_bit(&mut self) -> &mut [u16] {
        &mut self.data[368..370]
    }
    pub fn eob_base_y_tok_hf(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 372 + i * 16 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn base_y_tok_hf(&mut self, i: usize, j: usize, k: usize) -> &mut [u16] {
        let o = 452 + i * 160 + j * 8 + k * 4;
        &mut self.data[o..o + 4]
    }
    pub fn br_y_tok_hf(&mut self, j: usize) -> &mut [u16] {
        let o = 1252 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn eob_base_y_tok_lf(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 1280 + i * 32 + j * 8;
        &mut self.data[o..o + 8]
    }
    pub fn base_y_tok_lf(&mut self, i: usize, j: usize, k: usize) -> &mut [u16] {
        let o = 1440 + i * 528 + j * 16 + k * 8;
        &mut self.data[o..o + 8]
    }
    pub fn br_y_tok_lf(&mut self, j: usize) -> &mut [u16] {
        let o = 4080 + j * 4;
        &mut self.data[o..o + 4]
    }
    /// Parity-hidden DC token (dav2d 7f59d85). Kept after the C layout rather
    /// than at its C position, so no existing offset moves.
    pub fn ph_dc_y_tok(&mut self, ctx: usize) -> &mut [u16] {
        let o = 4656 + ctx * 4;
        &mut self.data[o..o + 4]
    }
    pub fn dc_sign(&mut self, i: usize, j: usize, k: usize) -> &mut [u16] {
        let o = 4136 + i * 12 + j * 6 + k * 2;
        &mut self.data[o..o + 2]
    }
    pub fn bob_base_y_tok(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 4160 + i * 12 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn br_y_tok_idtx(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 4196 + i * 28 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn base_y_tok_idtx(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 4280 + i * 28 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn sign_idtx(&mut self, i: usize, j: usize) -> &mut [u16] {
        let o = 4364 + i * 18 + j * 2;
        &mut self.data[o..o + 2]
    }
    pub fn eob_base_uv_tok_hf(&mut self, j: usize) -> &mut [u16] {
        let o = 4444 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn base_uv_tok_hf(&mut self, j: usize) -> &mut [u16] {
        let o = 4460 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn br_uv_tok_hf(&mut self, j: usize) -> &mut [u16] {
        let o = 4508 + j * 4;
        &mut self.data[o..o + 4]
    }
    pub fn eob_base_uv_tok_lf(&mut self, j: usize) -> &mut [u16] {
        let o = 4528 + j * 8;
        &mut self.data[o..o + 8]
    }
    pub fn base_uv_tok_lf(&mut self, j: usize) -> &mut [u16] {
        let o = 4560 + j * 8;
        &mut self.data[o..o + 8]
    }
}

