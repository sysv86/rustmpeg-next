/// Dynamic Q-value approximation parameters derived from `qstep` for Wiener classification.
#[derive(Clone, Copy, Debug)]
pub struct WienerQValApproxData {
    /// Offsets for 3 directional modes [vertical, anti-diag, diag].
    pub offsets: [i32; 3],
    /// Slopes for 3 directional modes.
    pub slopes: [i16; 3],
    /// Changeover threshold index for first directional mode.
    pub idx0_changeover: i16,
    /// Precomputed error LUT (3 modes x 64 entries).
    pub error_lut: [i32; 192],
}

impl Default for WienerQValApproxData {
    fn default() -> Self {
        Self {
            offsets: [0; 3],
            slopes: [0; 3],
            idx0_changeover: 0,
            error_lut: [0; 192],
        }
    }
}

/// Derives Wiener Q-value approximation data and class LUT base offset from `qstep`.
pub fn setup_wiener_qval_approx_data(qstep: i32) -> (WienerQValApproxData, usize) {
    let mut data = WienerQValApproxData::default();
    const MODE_WEIGHTS: [[i16; 3]; 4] = [
        [-527, 15325, 321],
        [26436, -17705, 17905],
        [366, -147, -194],
        [202, -267, -179],
    ];
    const MODE_OFFSETS: [i16; 4] = [-547, -21565, -573, -680];

    let mut init_idx0 = 0i32;
    let mut idx0_low = 0i32;
    let mut idx0_changeover = -1i16;

    for s in 0..=36i32 {
        let tskip = s * 7;
        let prod = (tskip * qstep + 128) >> 8;
        let qval_raw = (MODE_WEIGHTS[0][0] as i32) * (tskip << 5)
            + (MODE_WEIGHTS[0][1] as i32) * qstep
            + (MODE_WEIGHTS[0][2] as i32) * prod;
        let abs_qval = qval_raw.abs();
        let qval_signed = apply_sign((abs_qval + 4096) >> 13, qval_raw);
        let qval_sc = 255 * (MODE_OFFSETS[0] as i32 + qval_signed);
        let qval = ((qval_sc.max(0) + 8192) >> 14).min(255) >> 5;

        if s == 0 {
            init_idx0 = qval;
            idx0_low = qval;
        } else if qval != init_idx0 {
            idx0_low = qval;
            idx0_changeover = s as i16;
            break;
        }
    }
    data.idx0_changeover = idx0_changeover;
    let class_lut_offset = (idx0_low << 9) as usize;

    let mut tmp_table = [0i32; 37];
    for i in 0..3 {
        let slope_raw = 7 * 32 * (MODE_WEIGHTS[i + 1][0] as i32)
            + ((7 * (MODE_WEIGHTS[i + 1][2] as i64) * (qstep as i64)) >> 8) as i32;
        let slope = (slope_raw + 4096) >> 13;

        for s in 0..=36i32 {
            let tskip = s * 7;
            let prod = (tskip * qstep + 128) >> 8;
            let qval_raw = (MODE_WEIGHTS[i + 1][0] as i32) * (tskip << 5)
                + (MODE_WEIGHTS[i + 1][1] as i32) * qstep
                + (MODE_WEIGHTS[i + 1][2] as i32) * prod;
            let abs_qval = qval_raw.abs();
            let qval_signed = apply_sign((abs_qval + 4096) >> 13, qval_raw);
            let qval = MODE_OFFSETS[i + 1] as i32 + qval_signed;
            tmp_table[s as usize] = qval - s * slope;
        }

        data.slopes[i] = slope as i16;
        data.offsets[i] = tmp_table[0];
        for s in 0..=36usize {
            data.error_lut[i * 64 + s] = tmp_table[s] - tmp_table[0];
        }
    }

    (data, class_lut_offset)
}

