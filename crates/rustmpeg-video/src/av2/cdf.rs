    pub fn new(base_q_idx: u16) -> Self {
        let qcat = cdf_thread_init_static_qcat(base_q_idx as u32) as usize;
        Self {
            m: DEFAULT_MODE_CDF,
            coef: DEFAULT_COEF_CDF[qcat],
            mv: DEFAULT_MV_CDF,
            dmv: DEFAULT_MV_CDF,
        }
    }

