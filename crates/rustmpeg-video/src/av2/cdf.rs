//! Normative AV2 Specification v1.0.0 §6.17.2 & §9.3 Default CDF Tables (`init_non_coeff_cdfs`,
//! `init_coeff_cdfs`, `blend_cdf`, `avg_cdf`, `load_cdfs`).
//!
//! Every probability table in [`CdfModeContext`], [`CdfCoefContext`], and [`CdfMvContext`] is
//! initialized verbatim from the normative `Default_*_Cdf` tables in AV2 Specification v1.0.0
//! Section 9.3 (`attachments/default_*_cdf.h`). Each `N`-symbol CDF row has length `N + 1`:
//! `[cdf[0], ..., cdf[N - 2], para, count]`, where `cdf[0..N - 2]` are forward 15-bit cumulative
//! probabilities in `(0, 32768)`, `cdf[N - 1]` is the adaptation rate parameter index `para`
//! (`0..=124` into `Para_Adjustment_List`), and `cdf[N]` is the symbol counter (`0..=32`).

